#!/usr/bin/env node
// Generate packages/octocode-native/crates/engine/src/lsp/managed.lock.json from
// the GitHub release API, so no person types a hash (issue #481).
//
//   node skills-dev/octocode-dev/scripts/dev.mjs lsp:lock           regenerate the lock
//   node skills-dev/octocode-dev/scripts/dev.mjs lsp:lock --check   re-read GitHub, fail on any difference
//   node skills-dev/octocode-dev/scripts/dev.mjs lsp:lock --bump    move each server to its latest release
//
// The manifest (repository, release tag, asset names) is read from the
// `SERVERS` table in managed.rs, the one place a person declares it. For each
// asset it names, the lock records GitHub's upload-time `digest`, the size and
// the download URL. Generation fails when an asset is missing, when a digest is
// null or not `sha256:` plus 64 hex characters, or when two different assets
// share a digest. A token in GITHUB_TOKEN or GH_TOKEN (else `gh auth token`)
// raises the API limit from 60 to 5000 requests an hour.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { isMainModule } from './lib/entrypoint.mjs';
import { ROOT } from './lib/workspaces.mjs';

const LSP_DIR = path.join(ROOT, 'packages/octocode-native/crates/engine/src/lsp');
export const MANIFEST_PATH = path.join(LSP_DIR, 'managed.rs');
export const LOCK_PATH = path.join(LSP_DIR, 'managed.lock.json');
const API = 'https://api.github.com';
const NOTE = 'Generated by `node skills-dev/octocode-dev/scripts/dev.mjs lsp:lock` from the GitHub release API; regenerate, never edit.';

/** The `SERVERS` table of managed.rs: [{ name, repo, tag, assets: [{ platform, template }] }]. */
export function parseManifest(source) {
  const start = source.indexOf('const SERVERS: &[ServerDecl] = &[');
  if (start < 0) throw new Error('managed.rs has no `const SERVERS: &[ServerDecl] = &[` table');
  const end = source.indexOf('\n];', start);
  if (end < 0) throw new Error('managed.rs: the SERVERS table has no closing `];` line');
  const table = source.slice(start, end);
  const token = /\b(name|repo|release_tag):\s*"([^"]*)"|\b(?:zip|gz)\(\s*"([^"]+)",\s*"([^"]+)"/g;
  const servers = [];
  for (const match of table.matchAll(token)) {
    const [, field, value, platform, template] = match;
    if (field === 'name') servers.push({ name: value, assets: [] });
    else if (!servers.length) throw new Error(`managed.rs: \`${match[0]}\` comes before any server name`);
    else if (field === 'repo') servers.at(-1).repo = value;
    else if (field === 'release_tag') servers.at(-1).tag = value;
    else servers.at(-1).assets.push({ platform, template });
  }
  for (const server of servers) {
    if (!server.repo || !server.tag || !server.assets.length) {
      throw new Error(`managed.rs: server ${server.name} needs a repo, a release_tag and at least one asset`);
    }
  }
  if (!servers.length) throw new Error('managed.rs: the SERVERS table declares no server');
  return servers;
}

/** The asset names a server's templates expand to, without duplicates. */
export function assetNames(server) {
  return [...new Set(server.assets.map(({ template }) => template.replaceAll('{tag}', server.tag)))];
}

const DIGEST = /^sha256:([0-9a-f]{64})$/;

/**
 * The lock for `servers` from their releases (`releases[name]` is the API's
 * release JSON). Throws on a missing asset, a null or malformed digest, or a
 * digest two different assets share.
 */
export function buildLock(servers, releases) {
  const owners = new Map();
  const locked = {};
  for (const server of servers) {
    const release = releases[server.name];
    if (!release) throw new Error(`${server.name}: no release JSON for ${server.repo}@${server.tag}`);
    if (release.tag_name !== server.tag) {
      throw new Error(`${server.name}: GitHub answered tag ${release.tag_name} for ${server.tag}`);
    }
    const assets = {};
    for (const name of assetNames(server).sort()) {
      const asset = (release.assets ?? []).find(candidate => candidate.name === name);
      if (!asset) throw new Error(`${server.name}: release ${server.repo}@${server.tag} has no asset ${name}`);
      const digest = DIGEST.exec(asset.digest ?? '');
      if (!digest) {
        throw new Error(`${server.name}: asset ${name} has digest ${JSON.stringify(asset.digest ?? null)}, not sha256:<64 hex>`);
      }
      const sha256 = digest[1];
      const owner = owners.get(sha256);
      if (owner && owner !== `${server.repo}/${name}`) {
        throw new Error(`${server.name}: asset ${name} shares digest ${sha256} with ${owner}`);
      }
      owners.set(sha256, `${server.repo}/${name}`);
      if (!Number.isSafeInteger(asset.size) || asset.size <= 0) throw new Error(`${server.name}: asset ${name} has no size`);
      assets[name] = { sha256, size: asset.size, url: asset.browser_download_url };
    }
    if (typeof release.immutable !== 'boolean') throw new Error(`${server.name}: the release JSON has no immutable flag`);
    locked[server.name] = {
      assets,
      immutable: release.immutable,
      repo: server.repo,
      tag: server.tag,
    };
  }
  return { note: NOTE, servers: locked };
}

export const renderLock = lock => `${JSON.stringify(lock, null, 2)}\n`;

/** Human-readable differences between two locks, one line per changed value. */
export function diffLocks(before, after, prefix = '') {
  const keys = new Set([...Object.keys(before ?? {}), ...Object.keys(after ?? {})]);
  return [...keys].sort().flatMap(key => {
    const [a, b] = [before?.[key], after?.[key]];
    const where = prefix ? `${prefix}.${key}` : key;
    if (a && b && typeof a === 'object' && typeof b === 'object') return diffLocks(a, b, where);
    return JSON.stringify(a) === JSON.stringify(b) ? [] : [`${where}: ${JSON.stringify(a)} -> ${JSON.stringify(b)}`];
  });
}

/** managed.rs with `server`'s release_tag literal set to `tag`. */
export function withReleaseTag(source, server, tag) {
  const block = new RegExp(`(name:\\s*"${server.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"[\\s\\S]*?release_tag:\\s*")([^"]*)(")`);
  if (!block.test(source)) throw new Error(`managed.rs: no release_tag for ${server.name}`);
  return source.replace(block, (_, head, _old, tail) => `${head}${tag}${tail}`);
}

function token() {
  const fromEnv = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  if (fromEnv) return fromEnv;
  const gh = spawnSync('gh', ['auth', 'token'], { encoding: 'utf8' });
  return gh.status === 0 ? gh.stdout.trim() || undefined : undefined;
}

async function api(route, auth) {
  const headers = { accept: 'application/vnd.github+json', 'x-github-api-version': '2022-11-28' };
  if (auth) headers.authorization = `Bearer ${auth}`;
  const response = await fetch(`${API}${route}`, { headers });
  if (!response.ok) throw new Error(`GET ${route}: HTTP ${response.status} ${await response.text()}`);
  return response.json();
}

async function main() {
  const args = process.argv.slice(2);
  const unknown = args.filter(arg => !['--check', '--bump'].includes(arg));
  if (unknown.length || (args.includes('--check') && args.includes('--bump'))) {
    console.error('usage: lsp-lock.mjs [--check | --bump]');
    process.exit(2);
  }
  const auth = token();
  let source = readFileSync(MANIFEST_PATH, 'utf8');
  let servers = parseManifest(source);
  if (args.includes('--bump')) {
    for (const server of servers) {
      const latest = (await api(`/repos/${server.repo}/releases/latest`, auth)).tag_name;
      if (latest !== server.tag) {
        console.log(`${server.name}: ${server.tag} -> ${latest}`);
        source = withReleaseTag(source, server, latest);
      }
    }
    servers = parseManifest(source);
  }
  const releases = {};
  for (const server of servers) {
    releases[server.name] = await api(`/repos/${server.repo}/releases/tags/${encodeURIComponent(server.tag)}`, auth);
  }
  const lock = buildLock(servers, releases);
  if (args.includes('--check')) {
    let current;
    try {
      current = JSON.parse(readFileSync(LOCK_PATH, 'utf8'));
    } catch (error) {
      throw new Error(`${path.relative(ROOT, LOCK_PATH)} is unreadable (${error.message}); run lsp:lock`);
    }
    const changes = diffLocks(current, lock);
    if (changes.length) {
      console.error(`lsp:lock --check: ${path.relative(ROOT, LOCK_PATH)} differs from GitHub (an asset changed upstream, or the manifest changed without lsp:lock):`);
      for (const change of changes) console.error(`  ${change}`);
      process.exit(1);
    }
    console.log(`lsp:lock --check: ${servers.map(s => `${s.name}@${s.tag}`).join(', ')} match GitHub`);
    return;
  }
  if (args.includes('--bump')) writeFileSync(MANIFEST_PATH, source);
  writeFileSync(LOCK_PATH, renderLock(lock));
  console.log(`lsp:lock: wrote ${path.relative(ROOT, LOCK_PATH)} for ${servers.map(s => `${s.name}@${s.tag}`).join(', ')}`);
}

if (isMainModule(import.meta.url)) {
  main().catch(error => {
    console.error(`lsp:lock: ${error.message}`);
    process.exit(1);
  });
}
