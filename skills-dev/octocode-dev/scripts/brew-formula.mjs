#!/usr/bin/env node
// Render the Homebrew formula for the native `octocode` binary from the
// PUBLISHED npm platform packages. The tap (github.com/bgauryy/homebrew-octocode)
// receives a copy of the output; this repo is the formula's single source.
//
//   node skills-dev/octocode-dev/scripts/dev.mjs brew:formula [version] [--out FILE]
//
// Version defaults to the `latest` dist-tag of @octocodeai/octocode-native.
// Hashes are computed from the registry's bytes, never from a local `npm pack`
// (a repack is not guaranteed to be byte-identical). The host platform's
// binary is extracted and must report `octocode <version>`, the formula's test.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT } from './lib/workspaces.mjs';

const REGISTRY = 'https://registry.npmjs.org';
const PACKAGE = '@octocodeai/octocode-native';
// Homebrew os/arch → npm platform package. Linux uses the glibc builds (glibc ≥ 2.30).
const TARGETS = {
  macos: { arm: 'darwin-arm64', intel: 'darwin-x64' },
  linux: { arm: 'linux-arm64-gnu', intel: 'linux-x64-gnu' },
};

const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const out = path.resolve(
  outIndex >= 0 ? args[outIndex + 1] : path.join(ROOT, 'packages/octocode-native/homebrew/octocode.rb')
);
const requested = args.find((arg, index) => !arg.startsWith('--') && index !== outIndex + 1);

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

// npm platform package this machine can execute; Linux hosts are assumed glibc.
const HOST = `${process.platform}-${process.arch}${process.platform === 'linux' ? '-gnu' : ''}`;

/** Throws unless the tarball's `package/octocode` prints `octocode <version>`. */
function checkBinaryVersion(tarball, platform, version) {
  const dir = mkdtempSync(path.join(tmpdir(), 'octocode-brew-'));
  try {
    writeFileSync(path.join(dir, 'pkg.tgz'), tarball);
    execFileSync('tar', ['-xzf', 'pkg.tgz', 'package/octocode'], { cwd: dir });
    const reported = execFileSync(path.join(dir, 'package', 'octocode'), ['--version'], { encoding: 'utf8' }).trim();
    if (reported !== `octocode ${version}`) {
      throw new Error(`${PACKAGE}-${platform}@${version} ships a binary that reports "${reported}"; republish with a fresh build before rendering the formula.`);
    }
    console.log(`${platform.padEnd(16)} binary reports ${reported}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export function renderFormula(blocks) {
  const arch = (os, cpu) => `    on_${cpu} do
      url "${blocks[os][cpu].url}"
      sha256 "${blocks[os][cpu].sha256}"
    end`;

  return `# Generated by skills-dev/octocode-dev/scripts/brew-formula.mjs in github.com/bgauryy/octocode
# from the published npm packages; regenerate there instead of editing this file.
class Octocode < Formula
  desc "Code research CLI for local code, GitHub, LSP, and package registries"
  homepage "https://octocode.ai"
  license "MIT"

  # The npm URL selects livecheck's Npm strategy.
  livecheck do
    url :stable
  end

  on_macos do
${arch('macos', 'arm')}
${arch('macos', 'intel')}
  end

  on_linux do
${arch('linux', 'arm')}
${arch('linux', 'intel')}
  end

  def install
    bin.install "octocode"
  end

  test do
    assert_match "octocode #{version}", shell_output("#{bin}/octocode --version")
    (testpath/"notes.txt").write "alpha\\nneedle beta\\n"
    query = '{"queries":[{"path":"notes.txt","matchString":["needle b[a-z]+"],"regexEngine":"rust"}]}'
    assert_match '"line":2,"value":"needle beta"', shell_output("#{bin}/octocode localSearch '#{query}' --json")
  end
end
`;
}

async function main() {
  const version = requested ?? (await json(`${REGISTRY}/${PACKAGE}/latest`)).version;
  const blocks = {};
  for (const [os, arches] of Object.entries(TARGETS)) {
    blocks[os] = {};
    for (const [arch, platform] of Object.entries(arches)) {
      const name = `${PACKAGE}-${platform}`;
      const { dist } = await json(`${REGISTRY}/${name}/${version}`);
      const tarball = await download(dist.tarball);
      if (platform === HOST) checkBinaryVersion(tarball, platform, version);
      blocks[os][arch] = { url: dist.tarball, sha256: createHash('sha256').update(tarball).digest('hex') };
      console.log(`${platform.padEnd(16)} ${blocks[os][arch].sha256}`);
    }
  }

  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, renderFormula(blocks));
  console.log(`✓ ${path.relative(ROOT, out)} (octocode ${version})`);
  console.log('  Next: copy it to bgauryy/homebrew-octocode Formula/octocode.rb, then brew audit + brew install there.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
