#!/usr/bin/env node
// Shrink-only baseline of the oxlint violations that existed when a rule was adopted.
// Run it from the directory that holds .oxlintrc.json. That config extends
// .oxlintrc.baseline.json, which holds one override per file: a count rule switched off,
// or a size rule (max-lines, complexity, ...) raised to the file's current worst value.
// The baseline may only shrink. The same file serves octocode (skills-dev/octocode-dev/scripts)
// and octocode-mcp-host/packages/octocode-core/scripts; keep the two copies identical.
//   check (default): fails when an entry is stale (the file is now cleaner than its entry)
//                    or a violation has no entry (fix the code; never add entries by hand)
//   --write:         rewrites the file as the entries still needed, never adding one;
//                    creates the file when it does not exist yet
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = process.cwd();
const CONFIG = '.oxlintrc.json';
const BASELINE = '.oxlintrc.baseline.json';
const HEADER =
  '// Generated by oxlint-baseline.mjs: oxlint violations that predate the rules, one override per file.\n' +
  '// It may only shrink. Fix the code, then run the script with --write; never add or raise an entry by hand.\n';
// Rules whose diagnostics report a measured size; their entries raise the limit instead of switching the rule off.
const SIZE_RULES = new Set(['max-lines', 'max-lines-per-function', 'complexity', 'max-depth', 'max-params']);

/** `eslint(max-lines)` → `max-lines`; `typescript(no-explicit-any)` → `typescript/no-explicit-any`. */
export function ruleName(code) {
  const match = /^([\w-]+)\((.+)\)$/.exec(code ?? '');
  if (!match) return undefined;
  return match[1] === 'eslint' ? match[2] : `${match[1]}/${match[2]}`;
}

/** The measured size in a size-rule message: "complexity of 26", "too many lines (150)". */
export function measuredSize(message) {
  const match = /complexity of (\d+)|\((\d+)\)/.exec(message);
  return match ? Number(match[1] ?? match[2]) : undefined;
}

function sizeSetting(baseRule, size) {
  const [severity, options = {}] = Array.isArray(baseRule) ? baseRule : [baseRule];
  return [severity, { ...options, max: size }];
}

/**
 * The entries the diagnostics need: Map<file, Map<rule, "off" | [severity, options]>>.
 * Diagnostics no entry can hold (parse errors, invalid tsconfig) are returned as `unbaselinable`.
 */
export function neededEntries(diagnostics, baseRules) {
  const entries = new Map();
  const unbaselinable = [];
  for (const diagnostic of diagnostics) {
    const rule = ruleName(diagnostic.code);
    const size = SIZE_RULES.has(rule) ? measuredSize(diagnostic.message) : undefined;
    if (!rule || rule === 'typescript/tsconfig-error' || (SIZE_RULES.has(rule) && size === undefined)) {
      unbaselinable.push(diagnostic);
      continue;
    }
    const rules = entries.get(diagnostic.filename) ?? new Map();
    entries.set(diagnostic.filename, rules);
    if (!SIZE_RULES.has(rule)) rules.set(rule, 'off');
    else if (size > (rules.get(rule)?.[1].max ?? 0)) rules.set(rule, sizeSetting(baseRules[rule], size));
  }
  return { entries, unbaselinable };
}

const limitOf = setting => (setting === 'off' ? Infinity : setting[1].max);

/** Compares committed entries with needed ones: `stale` may shrink, `missing` are new violations. */
export function compareEntries(committed, needed) {
  const stale = [];
  const missing = [];
  for (const [file, rules] of committed) {
    for (const [rule, setting] of rules) {
      const need = needed.get(file)?.get(rule);
      if (need === undefined) stale.push({ file, rule, from: setting, to: undefined });
      else if (limitOf(need) < limitOf(setting)) stale.push({ file, rule, from: setting, to: need });
    }
  }
  for (const [file, rules] of needed) {
    for (const [rule, setting] of rules) {
      const have = committed.get(file)?.get(rule);
      if (have === undefined || limitOf(setting) > limitOf(have)) missing.push({ file, rule, need: setting });
    }
  }
  return { stale, missing };
}

/** The committed entries narrowed to what is still needed; never adds or raises one. */
export function shrinkEntries(committed, needed) {
  const shrunk = new Map();
  for (const [file, rules] of committed) {
    for (const [rule, setting] of rules) {
      const need = needed.get(file)?.get(rule);
      if (need === undefined) continue;
      const kept = shrunk.get(file) ?? new Map();
      kept.set(rule, limitOf(need) < limitOf(setting) ? need : setting);
      shrunk.set(file, kept);
    }
  }
  return shrunk;
}

const byText = (a, b) => a.localeCompare(b);

export function toConfig(entries) {
  const overrides = [...entries.keys()].toSorted(byText).map(file => ({
    files: [file],
    rules: Object.fromEntries([...entries.get(file)].toSorted(([a], [b]) => byText(a, b))),
  }));
  return { overrides };
}

export function fromConfig(config) {
  const entries = new Map();
  for (const { files, rules } of config.overrides ?? []) {
    for (const file of files) entries.set(file, new Map(Object.entries(rules)));
  }
  return entries;
}

/** One override per line, so a shrink is a one-line diff. */
export function serialize(entries) {
  const lines = toConfig(entries).overrides.map(override => `    ${JSON.stringify(override)}`);
  return `${HEADER}{\n  "overrides": [\n${lines.join(',\n')}\n  ]\n}\n`;
}
/** Parses the JSON-with-comments that oxlint accepts: drops `//` and `/* *\/` comments outside strings. */
export function parse(text) {
  let json = '';
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '"') {
      const start = i;
      for (i++; text[i] !== '"'; i++) if (text[i] === '\\') i++;
      json += text.slice(start, i + 1);
    } else if (text.startsWith('//', i)) {
      i = text.indexOf('\n', i) - 1;
      if (i < 0) break;
    } else if (text.startsWith('/*', i)) {
      i = text.indexOf('*/', i) + 1;
    } else {
      json += text[i];
    }
  }
  return JSON.parse(json);
}

/** Workspace directories whose lint script runs oxlint; the package itself when it has no workspaces. */
function lintTargets() {
  const { workspaces } = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  if (!workspaces) return ['.'];
  return workspaces
    .flatMap(pattern => {
      const base = pattern.replace(/\/\*$/, '');
      if (base === pattern) return [pattern];
      return fs.readdirSync(path.join(ROOT, base)).map(name => `${base}/${name}`);
    })
    .filter(dir => {
      const manifest = path.join(ROOT, dir, 'package.json');
      return fs.existsSync(manifest) && /\boxlint\b/.test(JSON.parse(fs.readFileSync(manifest, 'utf8')).scripts?.lint ?? '');
    });
}

/** Runs oxlint with the root rules and no baseline over every workspace that lints with it. */
function lintWithoutBaseline(config) {
  const { extends: _baseline, ...rules } = config;
  const temporary = path.join(ROOT, `.oxlintrc.unbaselined-${process.pid}.json`);
  fs.writeFileSync(temporary, JSON.stringify(rules));
  try {
    // The package exports no bin path, so look the installed package up in the node_modules chain.
    const oxlint = createRequire(path.join(ROOT, 'package.json'))
      .resolve.paths('oxlint')
      .map(dir => path.join(dir, 'oxlint', 'bin', 'oxlint'))
      .find(file => fs.existsSync(file));
    if (!oxlint) throw new Error('oxlint is not installed; run yarn install');
    const result = spawnSync(
      process.execPath,
      [oxlint, '-c', temporary, '--type-aware', '--report-unused-disable-directives', '-f', 'json', ...lintTargets()],
      { cwd: ROOT, encoding: 'utf8', maxBuffer: 512 * 1024 * 1024 }
    );
    if (result.error) throw result.error;
    if (!result.stdout.trim()) throw new Error(`oxlint produced no report (exit ${result.status}): ${result.stderr}`);
    return JSON.parse(result.stdout).diagnostics;
  } finally {
    fs.rmSync(temporary, { force: true });
  }
}

const label = setting => (setting === undefined ? 'remove' : setting === 'off' ? 'off' : `max ${setting[1].max}`);
const packageOf = file => file.split('/').slice(0, 2).join('/');

function summary(entries) {
  const perPackage = new Map();
  for (const [file, rules] of entries) {
    const row = perPackage.get(packageOf(file)) ?? { files: 0, entries: 0 };
    row.files += 1;
    row.entries += rules.size;
    perPackage.set(packageOf(file), row);
  }
  return Object.fromEntries([...perPackage].toSorted(([a], [b]) => byText(a, b)));
}

/** Writes the shrunk baseline (or the first one); returns how many problems remain. */
function writeBaseline(baselinePath, committed, needed) {
  if (!committed) {
    fs.writeFileSync(baselinePath, serialize(needed));
    console.table(summary(needed));
    return 0;
  }
  const { stale, missing } = compareEntries(committed, needed);
  const shrunk = shrinkEntries(committed, needed);
  fs.writeFileSync(baselinePath, serialize(shrunk));
  console.log(`${BASELINE}: ${stale.length} entries shrunk or removed`);
  console.table(summary(shrunk));
  return reportMissing(missing);
}

function reportMissing(missing) {
  for (const { file, rule, need } of missing) {
    console.error(`new violation: ${file} ${rule} (${label(need)}); fix the code, the baseline only shrinks`);
  }
  return missing.length;
}

/** Checks the committed baseline; returns how many problems it found. */
function checkBaseline(committed, needed) {
  if (!committed) throw new Error(`${BASELINE} is missing; create it with --write`);
  const { stale, missing } = compareEntries(committed, needed);
  for (const { file, rule, from, to } of stale) {
    console.error(`stale baseline entry: ${file} ${rule} ${label(from)} → ${label(to)}; run oxlint-baseline.mjs --write`);
  }
  if (!stale.length && !missing.length) console.log(`${BASELINE}: up to date`);
  return stale.length + reportMissing(missing);
}

function main() {
  const config = parse(fs.readFileSync(path.join(ROOT, CONFIG), 'utf8'));
  const baselinePath = path.join(ROOT, BASELINE);
  const { entries: needed, unbaselinable } = neededEntries(lintWithoutBaseline(config), config.rules ?? {});
  for (const diagnostic of unbaselinable) {
    console.error(`${diagnostic.filename}: ${diagnostic.code ?? 'oxlint'}: ${diagnostic.message} (fix it; a baseline cannot hold it)`);
  }
  const committed = fs.existsSync(baselinePath) ? fromConfig(parse(fs.readFileSync(baselinePath, 'utf8'))) : undefined;
  const problems = process.argv.includes('--write')
    ? writeBaseline(baselinePath, committed, needed)
    : checkBaseline(committed, needed);
  process.exit(problems + unbaselinable.length ? 1 : 0);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) main();
