#!/usr/bin/env node
// Local clippy ratchet for packages/octocode-native (`dev.mjs lint:rust`; CI keeps plain clippy). Same contract as
// oxlint-baseline.mjs: lints adopted after code existed live in clippy-baseline.json, which may only shrink.
//   check (default): any other warning fails, as `-D warnings` does; for a RATCHET lint, a crate holding
//                    more findings than its entries fails, and one holding fewer is stale until --write
//   --write:         rewrites the file from the current findings; never raises a crate's total
//   --adopt:         adds the entries of a lint newly added to RATCHET; a reviewed change, once per lint
// Ratchets judge production code only, by crate rather than by file, because refactors move code between
// files all the time. A site the rule should really allow says why, in the code:
//   #[cfg_attr(octocode_clippy_ratchet, expect(clippy::disallowed_methods, reason = "..."))]
// Only this mode loads the bans and enables that cfg, so plain Clippy has no unfulfilled expectation.
// The banned paths and their reasons are in packages/octocode-native/clippy-ratchet.toml.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { isMainModule } from './lib/entrypoint.mjs';
import { NATIVE } from './rust-quality.mjs';

const BASELINE = path.join(NATIVE, 'clippy-baseline.json');
// Records the units each clippy run used, so `dev.mjs prune:rust` keeps them warm.
const { collectArtifacts, writeKeep } = createRequire(import.meta.url)(path.join(NATIVE, 'scripts', 'target-hygiene.cjs'));
const NOTE = 'Generated by rust-lint.mjs. It may only shrink: fix the code, then run the script with --write.';

// Passed on the command line, so plain `cargo clippy` is unchanged. A lint with no entry must stay at zero.
export const RATCHET = [
  'clippy::disallowed_methods',
  // Slicing a str panics off a char boundary: a Unicode defect a test with ASCII never sees.
  'clippy::string_slice',
  'clippy::cast_possible_truncation',
  'clippy::cast_sign_loss',
  'clippy::cast_possible_wrap',
  'clippy::redundant_clone',
  // Zero findings today; each is a defect class strong Rust projects keep out.
  'clippy::mem_forget',
  'clippy::rc_mutex',
  'clippy::mutex_atomic',
  'clippy::unused_result_ok',
  'clippy::fn_to_numeric_cast_any',
  'clippy::suspicious_xor_used_as_pow',
  'clippy::float_cmp_const',
  'clippy::get_unwrap',
  'clippy::try_err',
];

/** The ratchet key of a diagnostic: a disallowed call counts apart per banned path. */
export function ratchetKey(message) {
  const code = message.code?.code;
  if (!RATCHET.includes(code)) return undefined;
  if (code !== 'clippy::disallowed_methods') return code;
  const banned = /`([^`]+)`/.exec(message.message)?.[1];
  return banned ? `${code}(${banned})` : code;
}

const primaryFile = message => message.spans?.find(span => span.is_primary)?.file_name;
const crateOf = file => /^crates\/([^/]+)\//.exec(file)?.[1] ?? 'other';

/** { key: { crate: { file: count } } } from production compiler messages; build scripts do not count. */
export function collect(records) {
  const found = {};
  const seen = new Set();
  for (const record of records) {
    if (record.reason !== 'compiler-message' || record.target?.kind?.includes('custom-build')) continue;
    const key = ratchetKey(record.message);
    const file = primaryFile(record.message);
    const span = record.message.spans?.find(item => item.is_primary);
    if (!key || !file) continue;
    const identity = `${key} ${file}:${span.line_start}:${span.column_start}`;
    if (seen.has(identity)) continue;
    seen.add(identity);
    const crate = crateOf(file);
    found[key] ??= {};
    found[key][crate] ??= {};
    found[key][crate][file] = (found[key][crate][file] ?? 0) + 1;
  }
  return found;
}

const total = files => Object.values(files ?? {}).reduce((sum, count) => sum + count, 0);

/** Per lint and crate: `grown` fails as new code, `stale` asks for --write. Moving code between files is neither. */
export function compare(baseline, found) {
  const grown = [];
  const stale = [];
  for (const key of new Set([...Object.keys(baseline), ...Object.keys(found)])) {
    for (const crate of new Set([...Object.keys(baseline[key] ?? {}), ...Object.keys(found[key] ?? {})])) {
      const had = baseline[key]?.[crate];
      const has = found[key]?.[crate];
      if (total(has) > total(had)) grown.push({ key, crate, had: total(had), has: total(has), files: Object.keys(has).filter(file => has[file] > (had?.[file] ?? 0)) });
      else if (total(has) < total(had)) stale.push({ key, crate, had: total(had), has: total(has) });
    }
  }
  return { grown, stale };
}

/** What --write stores: current findings, except where a crate grew, which keeps its entry and still fails. */
export function shrink(baseline, found) {
  const next = {};
  for (const [key, crates] of Object.entries(baseline)) {
    for (const [crate, files] of Object.entries(crates)) {
      const has = found[key]?.[crate];
      const kept = total(has) > total(files) ? files : has;
      if (kept && total(kept) > 0) {
        next[key] ??= {};
        next[key][crate] = kept;
      }
    }
  }
  return next;
}

/** Adds what found holds under a key the baseline lacks. */
export function adopt(baseline, found) {
  const next = { ...baseline };
  for (const [key, crates] of Object.entries(found)) if (!(key in next)) next[key] = crates;
  return next;
}

function sorted(value) {
  if (Array.isArray(value) || typeof value !== 'object' || value === null) return value;
  return Object.fromEntries(Object.entries(value).toSorted(([a], [b]) => a.localeCompare(b)).map(([key, item]) => [key, sorted(item)]));
}

export function serialize(entries) {
  return `${JSON.stringify({ _note: NOTE, ...sorted(entries) }, null, 2)}\n`;
}

function readBaseline() {
  if (!fs.existsSync(BASELINE)) return {};
  const { _note, ...entries } = JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
  return entries;
}

/** clippy.toml's settings with the ratchet's bans, under target/: plain clippy never reads this. */
export function ratchetConfig(base, bans) {
  return `${base.replace(/^disallowed-methods = \[[\s\S]*?^\]\n/m, '')}${bans}`;
}

function writeConfig() {
  const dir = path.join(NATIVE, 'target', 'rust-lint');
  const text = ratchetConfig(fs.readFileSync(path.join(NATIVE, 'clippy.toml'), 'utf8'), fs.readFileSync(path.join(NATIVE, 'clippy-ratchet.toml'), 'utf8'));
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'clippy.toml');
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
  return dir;
}

/** Cargo/rustc arguments for this ratchet only; pair with ratchetConfig's custom bans. */
export function clippyArgs(allTargets = false) {
  const flags = RATCHET.flatMap(lint => ['-W', lint]);
  return ['clippy', '--locked', '--workspace', ...(allTargets ? ['--all-targets'] : []), '--all-features', '--message-format=json', '--', '--cfg', 'octocode_clippy_ratchet', ...flags];
}

function clippy(allTargets, confDir) {
  const run = spawnSync('cargo', clippyArgs(allTargets), {
    cwd: NATIVE,
    env: { ...process.env, CLIPPY_CONF_DIR: confDir },
    encoding: 'utf8',
    maxBuffer: 2 ** 31,
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  if (run.error) throw run.error;
  const records = run.stdout.split('\n').filter(Boolean).flatMap(line => {
    try {
      return [JSON.parse(line)];
    } catch {
      return [];
    }
  });
  const artifacts = collectArtifacts(records);
  if (artifacts.stems.size) writeKeep(allTargets ? 'lint-clippy-all-targets' : 'lint-clippy', artifacts, { success: run.status === 0 });
  return { status: run.status, records };
}

/** Everything a ratchet does not cover fails as under `-D warnings`. */
function reportOthers(records) {
  const shown = new Set();
  for (const { reason, message } of records) {
    if (reason !== 'compiler-message' || RATCHET.includes(message.code?.code)) continue;
    if (!['warning', 'error'].includes(message.level) || /generated \d+ warning|aborting due to|could not compile/.test(message.message)) continue;
    if (!shown.has(message.rendered)) process.stderr.write(message.rendered);
    shown.add(message.rendered);
  }
  return shown.size;
}

function main() {
  const confDir = writeConfig();
  const production = clippy(false, confDir);
  const all = production.status === 0 ? clippy(true, confDir) : production;
  const others = reportOthers(all.records);
  if (all.status !== 0 || others > 0) {
    console.error(`rust-lint: clippy failed (exit ${all.status}, ${others} diagnostics above)`);
    return 1;
  }
  const found = collect(production.records);
  const baseline = readBaseline();
  if (process.argv.includes('--adopt')) {
    fs.writeFileSync(BASELINE, serialize(adopt(baseline, found)));
    console.log('rust-lint: adopted new lints into clippy-baseline.json');
    return 0;
  }
  const { grown, stale } = compare(baseline, found);
  if (process.argv.includes('--write')) {
    fs.writeFileSync(BASELINE, serialize(shrink(baseline, found)));
    console.log(`rust-lint: clippy-baseline.json refreshed, ${stale.length} crate totals lowered`);
  } else {
    for (const { key, crate, had, has } of stale) console.error(`stale baseline: ${key} in ${crate} ${had} → ${has}; run rust-lint.mjs --write`);
  }
  for (const { key, crate, had, has, files } of grown) {
    console.error(`new violation: ${key} in ${crate}, ${had} → ${has}. Look in: ${files.join(', ')}. Fix the code, the baseline only shrinks; a ratchet-only exception says why with #[cfg_attr(octocode_clippy_ratchet, expect(..., reason))]`);
  }
  const problems = grown.length + (process.argv.includes('--write') ? 0 : stale.length);
  if (!problems) console.log('rust-lint: clippy clean, baseline up to date');
  return problems ? 1 : 0;
}

if (isMainModule(import.meta.url)) process.exit(main());
