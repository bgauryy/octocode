#!/usr/bin/env node
// Regenerates crates/runtime/src/tools/ast_graph/aliases/python_stdlib.txt, the Python standard-library
// module names the graph linker treats as external. Two authoritative inputs, no hand-held names:
//   1. `sys.stdlib_module_names` of the python3 that runs this script (the modules the interpreter ships);
//   2. typeshed's stdlib/VERSIONS entries with an upper bound (`asyncore: 3.0-3.11`): modules a past
//      Python shipped and a later one removed, which an importer targeting an older Python still means.
// Both are pinned so the file does not depend on who regenerates it: the interpreter must be on the
// PINNED_PYTHON line (the script refuses another) and typeshed is read at TYPESHED_REF, not `main`.
// Both pins land in the file's header. Bump a pin here, regenerate, and commit the new file; the
// engine build reads the committed file and never fetches.
// Usage: gen-python-stdlib.mjs [--python PATH] [--versions FILE|URL] [--out FILE]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainModule } from './lib/entrypoint.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const DEFAULT_OUT = join(
  REPO,
  'packages/octocode-native/crates/runtime/src/tools/ast_graph/aliases/python_stdlib.txt',
);
/** The Python line whose `sys.stdlib_module_names` the file records (`major.minor`). */
export const PINNED_PYTHON = '3.15';
/** The typeshed commit whose `stdlib/VERSIONS` the file records. */
export const TYPESHED_REF = 'b2764c4d5e2dd833e5c191ad0e905ef4b7f8cd59';
export const DEFAULT_VERSIONS = `https://raw.githubusercontent.com/python/typeshed/${TYPESHED_REF}/stdlib/VERSIONS`;

/** Throws unless `version` (`3.15.2`) is on the pinned Python line. */
export function assertPinnedPython(version) {
  if (version.split('.').slice(0, 2).join('.') !== PINNED_PYTHON) {
    throw new Error(
      `python3 is ${version}; the stdlib list is pinned to Python ${PINNED_PYTHON}.x: run with --python PATH of a ${PINNED_PYTHON} interpreter, or bump PINNED_PYTHON and regenerate`,
    );
  }
}

/** Top-level modules of a typeshed `VERSIONS` text whose range ends at some Python version. */
export function removedModules(versions) {
  const names = [];
  for (const raw of versions.split('\n')) {
    const line = raw.split('#')[0].trim();
    const [name, range] = line.split(':').map((part) => part.trim());
    if (!name || !range || name.includes('.')) continue;
    if (/-\s*\d/.test(range)) names.push(name);
  }
  return names;
}

/** The sorted file body: a comment header, then one module name per line. */
export function render(interpreterNames, removed, interpreter, versionsSource) {
  const names = [...new Set([...interpreterNames, ...removed])].sort();
  return [
    '# Python standard-library top-level modules; generated by',
    '# skills-dev/octocode-graph-dev/scripts/gen-python-stdlib.mjs, do not edit.',
    `# Sources: sys.stdlib_module_names of Python ${interpreter} (pinned line ${PINNED_PYTHON}); typeshed stdlib/VERSIONS entries removed in a later Python, at ${versionsSource}.`,
    ...names,
    '',
  ].join('\n');
}

async function readVersions(source) {
  if (/^https?:/.test(source)) {
    const response = await fetch(source);
    if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`);
    return response.text();
  }
  return readFileSync(source, 'utf8');
}

async function main(argv) {
  let versions = DEFAULT_VERSIONS;
  let out = DEFAULT_OUT;
  let python = 'python3';
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--versions') versions = argv[++i];
    else if (argv[i] === '--out') out = argv[++i];
    else if (argv[i] === '--python') python = argv[++i];
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  const probe = JSON.parse(
    execFileSync(
      python,
      ['-c', 'import json,sys;print(json.dumps([sys.version.split()[0],sorted(sys.stdlib_module_names)]))'],
      { encoding: 'utf8' },
    ),
  );
  const [interpreter, interpreterNames] = probe;
  assertPinnedPython(interpreter);
  const source = versions === DEFAULT_VERSIONS ? `typeshed ${TYPESHED_REF}` : versions;
  writeFileSync(out, render(interpreterNames, removedModules(await readVersions(versions)), interpreter, source));
  console.log(`wrote ${out}`);
}

if (isMainModule(import.meta.url)) await main(process.argv.slice(2));
