fn ingest_root(dir: &Path, root: &Path, keep: Option<usize>, refresh: bool) -> GraphOutput {
    ingest(
        &{
            let defaults = IngestOptions::default();
            IngestOptions {
                path: root.to_path_buf(),
                workspace: Some(dir.to_path_buf()),
                keep: keep.unwrap_or(defaults.keep),
                refresh,
                ..defaults
            }
        },
        &workspace_policy(dir),
        &ContentSecurity::new(),
        &NeverCancel,
        None,
    )
}

/// A published snapshot's answer, built now or the current snapshot of an
/// unchanged scope (`reused`): every selected input was extracted or reused
/// from the scope's fact cache, and nothing resumed an interrupted build.
fn assert_fresh_build(output: &GraphOutput) {
    assert_eq!(output.class, ExitClass::Success, "{}", output.value);
    assert_eq!(output.value["extraction"]["resumedFiles"], 0);
    assert_eq!(
        output.value["extraction"]["parsedFiles"]
            .as_u64()
            .unwrap_or(0)
            + output.value["extraction"]["reusedFiles"]
                .as_u64()
                .unwrap_or(0),
        output.value["scan"]["filesScanned"]
            .as_u64()
            .unwrap_or(u64::MAX),
        "an explicit build must account for its selected inputs: {}",
        output.value
    );
}

fn impacted(out: &GraphOutput) -> Vec<(String, u64)> {
    out.value["rows"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|row| {
            (
                row["id"].as_str().unwrap_or_default().to_owned(),
                row["depth"].as_u64().unwrap_or(99),
            )
        })
        .collect()
}
