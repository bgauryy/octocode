fn findings(out: &GraphOutput, detector: &str) -> Vec<String> {
    out.value["rows"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|row| row["detector"] == detector)
        .map(|row| row["subject"].as_str().unwrap_or_default().to_owned())
        .collect()
}

