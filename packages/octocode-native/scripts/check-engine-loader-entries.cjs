'use strict';

const { existsSync, readFileSync } = require('fs');
const { resolve, join } = require('path');

const root = join(__dirname, '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const errors = [];
const entry = pkg.exports?.['./engine'] ?? {};

for (const [condition, expectedSyntax] of [
  ['import', 'esm'],
  ['require', 'cjs'],
  ['types', 'types'],
]) {
  const target = entry[condition];
  if (!target) {
    errors.push(`exports["./engine"].${condition} is missing`);
    continue;
  }
  const path = resolve(root, target);
  if (!existsSync(path)) {
    errors.push(`${condition} entry ${target} does not exist`);
    continue;
  }
  const source = readFileSync(path, 'utf8');
  if (expectedSyntax === 'esm' && !/(^|\n)export\s/m.test(source)) {
    errors.push(`${target} is not an ESM facade`);
  }
  if (expectedSyntax === 'cjs' && !/module\.exports/.test(source)) {
    errors.push(`${target} is not a CommonJS loader`);
  }
  if (source.includes('auto-generated by NAPI-RS')) {
    errors.push(`${target} is a generated napi-rs entry instead of the canonical loader`);
  }
}

for (const legacy of ['./native.cjs', './bin/octocode.cjs', './bin/octocode-regex-worker.cjs']) {
  if (!pkg.exports?.[legacy]) errors.push(`legacy export ${legacy} is missing`);
}

if (errors.length) {
  console.error('loader:check failed:');
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}
console.log('loader:check ok: runtime, engine, legacy, and bin exports are explicit');
