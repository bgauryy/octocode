#!/usr/bin/env node
'use strict';
// Docs-drift gate: pins machine-derivable README/doc claims against the
// source that owns them. Prose drifted repeatedly this cycle (exit-code
// table, tool counts, continuation format, env-var names); schemas are
// pinned by tests but prose was not. Claims are derived from source text —
// not a built binary — so the gate is deterministic and never flakes on
// build state.
//
// Pinned claims (keep this list small and machine-derivable; see RFC
// post-audit-hardening-2026-09 R3 — shrink the set rather than loosen it):
//   1. README exit-code table ↔ EXIT CODES block in cli/mod.rs long_about
//   2. Root-README tool count ↔ the generated contract tool registry
//   3. docs/CONFIGURATION.md env-var names ↔ config sources (both ways for
//      config-contract.json source keys)
//   4. Active source/docs/examples contain no retired pre-v20 CLI grammar
//   5. ARCHITECTURE.md Ownership-table modules exist under crates/
//   6. Docs pass Cargo feature flags only to crates that declare [features]

const fs = require('node:fs');
const path = require('node:path');

const nativeRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(nativeRoot, '..', '..');

const read = (p) => fs.readFileSync(p, 'utf8');
const cliSource = read(path.join(nativeRoot, 'crates/cli/src/cli/mod.rs'));
const configContract = JSON.parse(
  read(path.join(repoRoot, 'packages/octocode-config/config-contract.json'))
);
const nativeReadme = read(path.join(nativeRoot, 'README.md'));
const nativeArchitecture = read(path.join(nativeRoot, 'ARCHITECTURE.md'));
const rootReadme = read(path.join(repoRoot, 'README.md'));
const configDoc = read(path.join(repoRoot, 'docs/CONFIGURATION.md'));
const generatedConfigDoc = read(path.join(repoRoot, 'docs/generated/CONFIG_SETTINGS.md'));
const completeConfigDocs = `${configDoc}\n${generatedConfigDoc}`;

const failures = [];
const fail = (claim, detail) => failures.push(`- ${claim}\n    ${detail}`);
const normalize = (s) =>
  s
    .replace(/[—–]/g, '-')
    .replace(/[`*]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

// 1. Exit-code table --------------------------------------------------------
// Source of truth: the `Exit codes:` block of ROOT_HELP (the root long_about).
const longAbout = cliSource.match(/Exit codes:\n(.*?)"#;/s);
if (!longAbout) {
  fail('exit codes', 'Exit codes block not found in cli/mod.rs ROOT_HELP');
} else {
  const sourceCodes = new Map();
  for (const line of longAbout[1].split('\n')) {
    const m = line.match(/^\s*(\d+)\s+(.*)$/);
    if (m) sourceCodes.set(m[1], normalize(m[2]));
  }
  const readmeCodes = new Map();
  for (const m of nativeReadme.matchAll(/^\|\s*`(\d+)`\s*\|\s*(.+?)\s*\|\s*$/gm)) {
    readmeCodes.set(m[1], normalize(m[2]));
  }
  for (const [code, meaning] of sourceCodes) {
    if (!readmeCodes.has(code)) {
      fail('exit codes', `code ${code} in cli/mod.rs long_about is missing from packages/octocode-native/README.md`);
    } else if (!readmeCodes.get(code).startsWith(meaning)) {
      fail(
        'exit codes',
        `code ${code}: README says "${readmeCodes.get(code)}" but cli/mod.rs says "${meaning}"`
      );
    }
  }
  for (const code of readmeCodes.keys()) {
    if (!sourceCodes.has(code)) {
      fail('exit codes', `code ${code} documented in README but absent from cli/mod.rs long_about`);
    }
  }
  if (sourceCodes.size === 0) fail('exit codes', 'no codes parsed from long_about (parser drift)');
}

// 2. Tool count -------------------------------------------------------------
// ToolId is generated by build.rs from this same contract; source-file regexes
// would create a second, stale registry when the generated enum moves.
const toolContract = JSON.parse(read(path.join(repoRoot, 'packages/octocode-config/contract/tool-contract.json')));
const claim = rootReadme.match(/(\d+) tools in the full discovery catalog/);
if (!toolContract.tools || Object.keys(toolContract.tools).length === 0) {
  fail('tool count', 'contract tool registry is missing or empty');
} else if (!claim) {
  fail('tool count', '"N tools in the full discovery catalog" claim not found in root README.md');
} else {
  const count = Object.keys(toolContract.tools).length;
  if (String(count) !== claim[1]) {
    fail('tool count', `root README claims ${claim[1]} tools; generated contract has ${count}`);
  }
}

// 3. Env-var names ----------------------------------------------------------
// Docs → code: every env var named in a CONFIGURATION.md table row must be
// read somewhere in product source — the native runtime or a package's
// TS/JS source (name typos, renames, and retired keys surface).
const sourceDirs = fs.readdirSync(path.join(nativeRoot, 'crates'))
  .map(crate => path.join(nativeRoot, 'crates', crate, 'src'))
  .filter(dir => fs.existsSync(dir));
for (const pkg of fs.readdirSync(path.join(repoRoot, 'packages'))) {
  const src = path.join(repoRoot, 'packages', pkg, 'src');
  if (fs.existsSync(src)) sourceDirs.push(src);
}
let runtimeSource = '';
const sourceExts = new Set(['.rs', '.ts', '.mts', '.cts', '.js', '.mjs', '.cjs']);
(function walkAll(dirs) {
  for (const dir of dirs) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name);
      if (entry.isDirectory()) walkAll([p]);
      else if (sourceExts.has(path.extname(entry.name))) runtimeSource += read(p);
    }
  }
})(sourceDirs);
const documentedKeys = new Set();
for (const m of configDoc.matchAll(/^\|\s*`([A-Z][A-Z0-9_]{2,})`\s*\|/gm)) {
  documentedKeys.add(m[1]);
}
for (const key of documentedKeys) {
  if (!runtimeSource.includes(key)) {
    fail('env names', `docs/CONFIGURATION.md documents ${key} but native or interface source never reads it`);
  }
}
// Code → docs: every configuration-source environment key in the canonical
// config contract must be mentioned in the guide or its generated reference.
const sourceKeys = new Set();
for (const [name, definition] of Object.entries(configContract.environment ?? {})) {
  if (definition.configSource === true) sourceKeys.add(name);
}
for (const section of Object.values(configContract.sections ?? {})) {
  for (const field of Object.values(section.fields ?? {})) {
    for (const name of Object.keys(field.env ?? {})) sourceKeys.add(name);
  }
}
for (const key of sourceKeys) {
  if (!completeConfigDocs.includes(key)) {
    fail('env names', `config-contract.json contains source key ${key} but configuration docs never mention it`);
  }
}

// 4. Retired CLI grammar ----------------------------------------------------
// Historical benchmark receipts keep their original commands. Everything
// else that is maintained must use `schema` and direct root tool commands.
const retiredQueriesFlag = /--queries\b/;
const retiredCliPatterns = [
  /\bnode\s+[^\n]*octocode(?:\.js)?\s+tools(?:\s|$)/,
  /\bnpx(?:\s+-y)?\s+octocode\s+tools(?:\s|$)/,
  /\bcontext\s+--(?:json|compact|minimal)\b/,
  /--scheme(?:-view)?\b/,
  /(?:\boctocode(?:\.js)?|\$OCTO)\s+scheme\b/,
  /\boctocode(?:\.js)?\s+showConfig\b/,
  /(?:\boctocode(?:\.js)?|\$OCTO)\s+[^\n]*--(?:json-errors|redact-emails|pretty)\b/,
  /(?:\boctocode(?:\.js)?|\$OCTO)\s+config\s+--(?:add|remove|check|value-stdin)\b/,
  retiredQueriesFlag,
  /\[\s*['"]tools['"]\s*,\s*['"][A-Za-z]/,
];
const schemaCliRoot = path.join(repoRoot, 'packages/octocode-mcp-cli');
function hasRetiredCliGrammar(line, file) {
  // The MCP-to-CLI library derives flags from arbitrary schemas. A queries
  // property legitimately becomes --queries there; it is a separate grammar.
  const schemaCli = file.startsWith(`${schemaCliRoot}${path.sep}`);
  const nativeInvocation = /(?:\boctocode(?:\.js)?|\$OCTO)\s+[^\n]*--queries\b/.test(line);
  return retiredCliPatterns.some((pattern) =>
    pattern === retiredQueriesFlag && schemaCli && !nativeInvocation
      ? false
      : pattern.test(line),
  );
}
const schemaCliDoc = path.join(schemaCliRoot, 'README.md');
if (
  hasRetiredCliGrammar('node examples/octocode-cli.ts localSearch --queries []', schemaCliDoc) ||
  !hasRetiredCliGrammar('node packages/octocode/out/octocode.js localSearch --queries []', schemaCliDoc) ||
  !hasRetiredCliGrammar('--queries []', path.join(repoRoot, 'docs/CONFIGURATION.md'))
) {
  fail('retired CLI grammar', 'the detector confuses schema-derived flags with the native CLI grammar');
}
const retiredCliSelfTest = [
  'node packages/octocode/out/octocode.js tools localFetch --scheme --json',
  'node packages/octocode/out/octocode.js scheme localFetch --view query',
  '$OCTO localSearch --pretty \'{}\'',
  'octocode config --add GITHUB_TOKEN x',
  "['tools', 'localFetch', '--queries', '{}']",
  'octocode context --compact',
];
if (retiredCliSelfTest.some((sample) => !retiredCliPatterns.some((pattern) => pattern.test(sample)))) {
  fail('retired CLI grammar', 'the detector self-test no longer recognizes a retired command shape');
}
if (
  retiredCliPatterns.some((pattern) =>
    pattern.test("node packages/octocode/out/octocode.js schema localFetch --view query --select operation=x"),
  )
) {
  fail('retired CLI grammar', 'the detector self-test rejects the current schema grammar');
}

const ignoredDirs = new Set([
  '.git',
  'releases',
  '.octocode',
  'node_modules',
  'out',
  'dist',
  'target',
  'coverage',
  'octocode-benchmark',
]);
const ignoredPaths = new Set([
  // Separate checkouts have their own validation; keep this scan in the current tree.
  path.join(repoRoot, '.claude/worktrees'),
  // Dated validation reports record the commands each run used.
  path.join(repoRoot, 'octocode-local-testing/validate/features'),
  path.join(repoRoot, 'packages/octocode-native/scripts/check-doc-claims.cjs'),
]);
// The research skill's guidance checker lists retired grammar as forbidden
// patterns; every staged copy of the skill (CLI package, plugins, releases)
// carries the same list.
const GUIDANCE_CHECKER_SUFFIX = path.join('skills', 'octocode-research', 'scripts', 'check-guidance.mjs');
const activeExtensions = new Set(['.md', '.rs', '.ts', '.mts', '.cts', '.js', '.mjs', '.cjs']);
const fixtureReposRoot = path.join(repoRoot, 'octocode-local-testing/repos');
function scanRetiredCliGrammar(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignoredDirs.has(entry.name)) continue;
    const file = path.join(dir, entry.name);
    if (ignoredPaths.has(file) || file.endsWith(GUIDANCE_CHECKER_SUFFIX)) continue;
    if (entry.isDirectory()) {
      // Downloaded third-party fixtures are not maintained Octocode source.
      // Keep checking the tracked README beside them.
      if (dir === fixtureReposRoot) continue;
      scanRetiredCliGrammar(file);
      continue;
    }
    if (!activeExtensions.has(path.extname(entry.name))) continue;
    const lines = read(file).split('\n');
    for (let index = 0; index < lines.length; index += 1) {
      if (hasRetiredCliGrammar(lines[index], file)) {
        fail(
          'retired CLI grammar',
          `${path.relative(repoRoot, file)}:${index + 1} still contains: ${lines[index].trim()}`,
        );
      }
    }
  }
}
scanRetiredCliGrammar(repoRoot);

// 5. Ownership modules -------------------------------------------------------
// Every backticked module in the Ownership table's first column must name a
// crate directory or a module under crates/runtime/src.
const ownership = nativeArchitecture.match(/^## Ownership\n([\s\S]*?)(?=^## )/m);
if (!ownership) {
  fail('ownership modules', 'Ownership section not found in ARCHITECTURE.md');
} else {
  const runtimeSrc = path.join(nativeRoot, 'crates/runtime/src');
  let rows = 0;
  for (const row of ownership[1].matchAll(/^\|([^|\n]+)\|/gm)) {
    for (const [, module] of row[1].matchAll(/`([^`]+)`/g)) {
      rows += 1;
      const candidates = module.startsWith('crates/')
        ? [path.join(nativeRoot, module)]
        : [path.join(runtimeSrc, module), path.join(runtimeSrc, `${module}.rs`)];
      if (!candidates.some((candidate) => fs.existsSync(candidate))) {
        fail('ownership modules', `ARCHITECTURE.md Ownership table names \`${module}\`, which does not exist`);
      }
    }
  }
  if (rows === 0) fail('ownership modules', 'no modules parsed from the Ownership table (parser drift)');
}

// 6. Cargo feature flags ----------------------------------------------------
const featurelessCrates = fs.readdirSync(path.join(nativeRoot, 'crates'))
  .map((crate) => path.join(nativeRoot, 'crates', crate, 'Cargo.toml'))
  .filter((manifest) => fs.existsSync(manifest))
  .map(read)
  .filter((manifest) => !/^\[features\]/m.test(manifest))
  .map((manifest) => manifest.match(/^name\s*=\s*"([^"]+)"/m)?.[1])
  .filter(Boolean);
const docsDir = path.join(nativeRoot, 'docs');
const featureDocs = [
  ['README.md', nativeReadme],
  ['ARCHITECTURE.md', nativeArchitecture],
  ...fs.readdirSync(docsDir)
    .filter((name) => name.endsWith('.md'))
    .map((name) => [`docs/${name}`, read(path.join(docsDir, name))]),
];
for (const [name, text] of featureDocs) {
  for (const line of text.split('\n')) {
    if (!/--no-default-features|--all-features/.test(line)) continue;
    for (const crate of featurelessCrates) {
      if (new RegExp(`-p ${crate}(?![\\w-])`).test(line)) {
        fail('cargo features', `${name} passes a feature flag to ${crate}, which declares no [features]: ${line.trim()}`);
      }
    }
  }
}

if (failures.length > 0) {
  console.error('check-doc-claims: pinned doc claims drifted from source:\n');
  console.error(failures.join('\n'));
  console.error('\nFix the doc (or the source) rather than loosening this gate.');
  process.exit(1);
}
console.log('check-doc-claims: all pinned doc claims match source.');
