#!/usr/bin/env node
// Generates docs/cdp-domains.md from a Chrome's own /json/protocol.
// Usage: node tools/gen-cdp-domains.mjs <port | protocol.json> [--out <file>] [--chrome <version text>]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromeDomainFamilies } from '@octocodeai/config/chrome';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const GETTER = /^(get|is|can|request|list|query)[A-Z]/;
const docsBase = 'https://chromedevtools.github.io/devtools-protocol/tot/';

/** Markdown for a protocol document; `chrome` names the Chrome it came from. */
export function renderDomains(protocol, chrome) {
  const families = new Map();
  for (const { family, domains } of chromeDomainFamilies)
    for (const { name } of domains)
      families.set(name, [...(families.get(name) ?? []), family]);
  const domains = [...protocol.domains].sort((a, b) =>
    a.domain.localeCompare(b.domain)
  );
  const status = d =>
    d.deprecated ? 'deprecated' : d.experimental ? 'experimental' : 'stable';
  const enable = d => {
    if (!d.commands?.some(c => c.name === 'enable')) return '-';
    return d.dependencies?.length
      ? `yes (needs ${d.dependencies.join(', ')})`
      : 'yes';
  };
  const getters = d =>
    (d.commands ?? [])
      .filter(
        c => GETTER.test(c.name) && !(c.parameters ?? []).some(p => !p.optional)
      )
      .map(c => c.name);
  const lines = [
    '# CDP domains',
    '',
    `Generated by \`tools/gen-cdp-domains.mjs\` from the protocol schema of ${chrome}. Do not edit; rerun the tool.`,
    '',
    `${domains.length} domains. \`protocol *\` lists the installed Chrome's own, \`protocol Domain\` the members and enable needs. Support family: the instruction map in the contract (\`other\` when it is not in the map).`,
    '',
    '| Domain | Status | Commands / events | Enable | Family | Docs |',
    '|---|---|---|---|---|---|',
    ...domains.map(
      d =>
        `| ${d.domain} | ${status(d)} | ${d.commands?.length ?? 0} / ${d.events?.length ?? 0} | ${enable(d)} | ${families.get(d.domain)?.join(', ') ?? 'other'} | [${d.domain}](${docsBase}${d.domain}/) |`
    ),
    '',
    '## Parameterless getters',
    '',
    'Commands named get*, is*, can*, request*, list* or query* with no required parameter: candidates for a first read (`check cdp-domain` dumps them into files); check the Enable column first.',
    '',
    ...domains
      .map(d => [d.domain, getters(d)])
      .filter(([, names]) => names.length)
      .map(([name, names]) => `- **${name}**: ${names.join(', ')}`),
    '',
  ];
  return lines.join('\n');
}

async function load(source) {
  if (/^\d+$/.test(source)) {
    const base = `http://127.0.0.1:${source}`;
    const version = await (await fetch(`${base}/json/version`)).json();
    const protocol = await (await fetch(`${base}/json/protocol`)).json();
    return { protocol, chrome: version.Browser };
  }
  return { protocol: JSON.parse(readFileSync(source, 'utf8')), chrome: null };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const option = name => {
    const at = args.indexOf(name);
    return at < 0 ? undefined : args.splice(at, 2)[1];
  };
  const out = resolve(option('--out') ?? join(root, 'docs/cdp-domains.md'));
  const chromeArg = option('--chrome');
  const [source] = args;
  if (!source) {
    process.stderr.write(
      'Usage: gen-cdp-domains.mjs <port | protocol.json> [--out file] [--chrome text]\n'
    );
    process.exit(2);
  }
  const { protocol, chrome } = await load(source);
  writeFileSync(
    out,
    renderDomains(
      protocol,
      chromeArg ?? chrome ?? 'a saved schema (Chrome version not recorded)'
    )
  );
  process.stdout.write(`${out}\n`);
}
