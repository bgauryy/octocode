// data.json (+ model.json beside it) -> brief.txt: measured facts only (counts, algorithm
// results, checks), each pointing to the data.json field that holds every row. The live viewer is serve.ts.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { flags } from './lib.ts';
import { computeMetrics } from './metrics.ts';
import { resolveModel } from './model.ts';
import { graphCli, graphCommand, shellArg } from './invocation.ts';
import { workspaceNote } from './workspace-scope.ts';
import type { ResolvedModel } from './model.ts';
import type {
  CallStats,
  Community,
  FileNode,
  GraphData,
  MeasuredGraph,
} from './types.ts';

const usage =
  () => `usage: ${graphCommand()} render --data <data.json> [--model <model.json>]
  Writes brief.txt beside data.json (computing graph metrics when data.json has none);
  --model (default: model.json beside it) adds the overlay and prints each problem to stderr.`;

// computeMetrics measured every file of a measured graph.
const metricsOf = (f: FileNode) => f.metrics!;
const top = (
  D: MeasuredGraph,
  key: 'pagerank' | 'betweenness' | 'inWeight',
  n: number
) =>
  [...D.files]
    .toSorted((a, b) => metricsOf(b)[key] - metricsOf(a)[key])
    .slice(0, n)
    .map(f => `${f.id} ${metricsOf(f)[key]}`)
    .join('; ');

// Unanswered LSP probes by the server's reason. Build-script-generated types (buildScriptsOff) stay invisible:
// rust-analyzer never runs the repository's build scripts, and the row's related localSearch reads those names.
function unansweredNote(cs: CallStats) {
  const list = cs.unanswered ?? [];
  const withheld = cs.withheld
    ? `; ${cs.withheld} answers omitted locations outside the allowed read roots (never graph files)`
    : '';
  if (!list.length) return withheld;
  const count = new Map<string, number>();
  for (const u of list)
    for (const r of u.reasons?.length ? u.reasons : ['unknown'])
      count.set(r, (count.get(r) ?? 0) + 1);
  const why = [...count].map(([r, k]) => `${r} ×${k}`).join(', ');
  const hint = count.has('buildScriptsOff')
    ? '; buildScriptsOff = types generated by build scripts, which are never run: the related localSearch reads them'
    : '';
  const partial = cs.partialWithMatches
    ? `, ${cs.partialWithMatches} with confirmed matches`
    : '';
  return `${withheld}; ${list.length} probes incomplete (${why})${partial}${hint}`;
}

// Communities (size > 1) ranked by the PageRank their members hold: label, size, summed PageRank, top member.
function rankedCommunities(D: MeasuredGraph) {
  const rank = new Map(D.files.map(f => [f.id, f.metrics?.pagerank ?? 0]));
  const of = (m: string) => rank.get(m) ?? 0;
  return D.metrics.communities
    .filter(c => c.size > 1)
    .map(c => {
      const lead = c.members.reduce(
        (a, m) => (of(m) > of(a) ? m : a),
        c.members[0]
      );
      return { ...c, pagerank: c.members.reduce((s, m) => s + of(m), 0), lead };
    })
    .toSorted((a, b) => b.pagerank - a.pagerank);
}

const communityLine = (c: Community & { pagerank: number; lead: string }) =>
  `${c.label} (${c.size} files, PageRank ${Number(c.pagerank.toPrecision(3))}, ${Math.round(c.purity * 100)}% in ${c.chunk}, top ${c.lead})`;

function partialLines(D: GraphData) {
  const coverage = D.coverage,
    snapshot = D.snapshot;
  const reasons = [
    ...new Set([
      ...(coverage.partialReasons ?? []),
      ...(snapshot?.partialReasons ?? []),
    ]),
  ];
  const missing = coverage.notBuilt ?? [];
  if (
    !coverage.isPartial &&
    !snapshot?.isPartial &&
    !reasons.length &&
    !missing.length
  )
    return [];
  const why = reasons.length ? reasons.join(', ') : 'reason not supplied';
  const chunks = missing.length
    ? `; chunks not built: ${missing.join(', ')}`
    : '';
  return [
    `COVERAGE PARTIAL: ${why}${chunks}. Counts and metrics cover observed evidence. Details: data.json coverage.partialChunks, coverage.notBuilt and snapshot.partialReasons.`,
  ];
}

// Docs → code links (links-docs.ts): counts by rule, unresolved references by reason, stale citations.
function linkLines(D: MeasuredGraph) {
  if (!D.links) return [];
  const by = <T>(list: readonly T[], key: (x: T) => string) =>
    Object.entries(
      list.reduce<Record<string, number>>((m, x) => {
        m[key(x)] = (m[key(x)] ?? 0) + 1;
        return m;
      }, {})
    )
      .map(([k, v]) => `${k} ${v}`)
      .join(', ');
  const unresolved = D.unresolvedLinks ?? [];
  const stale = D.links.filter(l => l.check === 'stale').length;
  return [
    `LINKS ${D.links.length} from docs (${by(D.links, l => l.rule) || 'none'}); ${unresolved.length} unresolved (${by(unresolved, u => u.reason) || 'none'}); ${stale} stale citations. Rows: query "links --unresolved", "links --stale"`,
  ];
}

function factLines(D: MeasuredGraph, n: number) {
  const C = D.coverage,
    M = D.metrics,
    s = M.stats,
    v = D.verification,
    cs = D.callStats;
  return [
    `SECTION ${D.section}: ${C.files} files, ${C.imports} imports, ${D.symbols.length} symbols in the call graph, ${C.calls} calls${(C.chunks ?? 0) > 1 ? `, ${C.built}/${C.chunks} chunks (${C.crossChunkImports} imports and ${C.crossChunkCalls} calls between chunks)` : ''}. Paths are relative to the section.`,
    // A root inside a workspace: its imported sibling packages are externals until the workspace root is built.
    ...(C.workspaceExternals ?? []).map(w => `SCOPE ${workspaceNote(w)}`),
    ...partialLines(D),
    `GRAPH ${s.nodes} nodes, ${s.edges} weighted production edges, total weight ${s.weight}; depth 0-${s.maxDepth}; max k-core ${s.maxCore}; modularity ${s.modularity} over ${s.communities} communities (+${s.isolated} isolated files)`,
    `COMMUNITIES by summed PageRank: ${rankedCommunities(D).slice(0, n).map(communityLine).join('; ')}`,
    `PAGERANK (weighted, importance flows to dependencies): ${top(D, 'pagerank', n)}`,
    `BETWEENNESS (bridges on shortest dependency paths): ${top(D, 'betweenness', n)}`,
    `IN-WEIGHT (imports + evidence-weighted calls received): ${top(D, 'inWeight', n)}`,
    `CYCLES ${s.cycles} strongly connected sets; ${M.cycles
      .slice(0, n)
      .map(
        c =>
          `${c.size} files [${c.languages.join(',')}] in ${c.chunks.join('+')}`
      )
      .join('; ')}`,
    `PACKAGES (Ca in, Ce out, I = Ce/(Ca+Ce)): ${M.packages
      .slice(0, n)
      .map(p => `${p.chunk} Ca ${p.ca} Ce ${p.ce} I ${p.instability}`)
      .join('; ')}`,
    `FILES checked on disk: ${v ? `${v.ok}/${v.checked} match (${v.stale} stale, ${v.missing} missing, ${v.lines} with lines outside the file${v.unverified ? `, ${v.unverified} freshness unverified` : ''})` : 'not checked'}`,
    ...linkLines(D),
    `CALLS ${cs?.lsp === 'ok' || cs?.lsp === 'partial' ? `cross-checked by LSP: ${cs.both} both, ${cs.graphOnly} graph only, ${cs.lspOnly} LSP only${unansweredNote(cs)}` : `graph only (${cs?.lsp ?? 'off'})`}`,
  ];
}

function modelLines(m: ResolvedModel) {
  return [
    `MODEL layers=${m.layers.map(l => l.id).join('>') || 'none'} upward_imports=${m.upward.length}${
      m.upward.length
        ? ` (${m.upward
            .slice(0, 3)
            .map(e => `${e.source}>${e.target}:${e.line}`)
            .join('; ')})`
        : ''
    } flows=${m.flows.map(x => x.id).join(',') || 'none'}`,
    ...m.findings.map(x => `FINDING [${x.confidence}] ${x.title}`),
    ...(m.warnings.length ? [`MODEL WARNINGS ${m.warnings.length}`] : []),
  ];
}

const where = (out: string) =>
  `Every row: ${graphCli(`query ${shellArg(out)} "top pagerank all"`)} (or betweenness, inweight, depth, core); data.json holds files[].metrics and .check, metrics.cycles/communities/packages and the weighted fileEdges.`;

// Writes brief.txt beside data.json, the measured facts an agent reads first; returns its path.
export function writeBrief(
  D: GraphData,
  out: string,
  modelPath = join(out, 'model.json')
) {
  if (!D.metrics) computeMetrics(D);
  // Measured: D had its metrics, or computeMetrics set them (and fileEdges) just now.
  const G = D as MeasuredGraph;
  if (existsSync(modelPath)) {
    const resolved = resolveModel(
      G,
      JSON.parse(readFileSync(modelPath, 'utf8'))
    );
    G.model = resolved;
    for (const w of resolved.warnings) process.stderr.write(`model: ${w}\n`);
  }
  // A model is only ever resolveModel's answer.
  const model = G.model as ResolvedModel | undefined;
  const full = [
    ...factLines(G, 5),
    `WEIGHT ${G.metrics.weightRule}`,
    ...(G.chunks ?? []).map(
      c =>
        `CHUNK ${c.path} files=${c.files} ${c.built ? 'built' : `not built${c.error ? `: ${c.error}` : ''}`}`
    ),
    ...(model ? modelLines(model) : []),
    where(out),
  ];
  const brief = join(out, 'brief.txt');
  writeFileSync(brief, `${full.join('\n')}\n`);
  return { brief };
}

export async function main() {
  if (process.argv.includes('--help')) {
    process.stdout.write(`${usage()}\n`);
    process.exit(0);
  }
  const f = flags(process.argv.slice(2), { data: '', model: '' });
  if (!f.data) {
    process.stderr.write(`${usage()}\n`);
    process.exit(2);
  }
  const dataPath = resolve(f.data);
  const out = dirname(dataPath);
  const D: GraphData = JSON.parse(readFileSync(dataPath, 'utf8'));
  process.stdout.write(
    `${JSON.stringify(writeBrief(D, out, f.model ? resolve(f.model) : undefined))}\n`
  );
}
