import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isObject, type Json } from './json.ts';
import { keepReachable, nativeIdentifiers } from './rust-reach.ts';

export const TYPIFY_VERSION = '0.8.0';

/** The header pins the bundle digest, so staleness is checkable without cargo. */
export const rustHeader = (fingerprint: string, schemaSha256: string): string =>
  `// @generated by @octocodeai/config scripts/generate-tool-contract.ts (cargo-typify ${TYPIFY_VERSION}); do not edit.
// Source: @octocodeai/octocode-core Zod contract ${fingerprint}.
pub const TOOL_TYPES_CONTRACT_FINGERPRINT: &str = ${JSON.stringify(fingerprint)};
pub const TOOL_TYPES_SCHEMA_SHA256: &str = ${JSON.stringify(schemaSha256)};
`;

function requireTypify(): void {
  let version = '';
  try {
    version = execFileSync('cargo', ['typify', '--version'], { encoding: 'utf8' });
  } catch {
    throw new Error(`cargo-typify is required: cargo install cargo-typify --version ${TYPIFY_VERSION} --locked`);
  }
  if (!version.includes(TYPIFY_VERSION)) {
    throw new Error(`cargo-typify ${TYPIFY_VERSION} is required (found ${version.trim()}).`);
  }
}

/**
 * The bundle as native needs it. Representation changes, applied here
 * and never to the published bundle:
 * - the per-tool `*Output` roots are dropped: native checks outputs against
 *   the JSON schema, so the types typify would expand from them (most of the
 *   file) are dead code; core-named shared definitions (`Selection`,
 *   `ArtifactType`, …) stay because native builds output fields from them;
 * - an `anyOf` over closed objects becomes `oneOf`, which typify emits as an
 *   enum (it flattens `anyOf` into a struct of optional subtypes). serde
 *   decodes such an enum by trying variants in order, so an input matching
 *   two branches still decodes; full validation stays with the JSON schema.
 * - unconstrained string property names are implicit in JSON objects; omit
 *   that redundant keyword because typify cannot merge it in object unions.
 * - ref-site titles/descriptions are annotations, not validation. typify's
 *   intersection merger rejects them; canonical definitions keep their names.
 */
export function rustBundle(bundle: { [key: string]: Json }): { [key: string]: Json } {
  const defs: { [key: string]: Json } = isObject(bundle.$defs) ? bundle.$defs : {};
  const closed = (branch: Json, seen = new Set<string>()): boolean => {
    if (branch === null || typeof branch !== 'object' || Array.isArray(branch)) return false;
    const ref = branch.$ref;
    if (typeof ref === 'string' && ref.startsWith('#/$defs/')) {
      const name = ref.slice('#/$defs/'.length);
      if (seen.has(name)) return false;
      seen.add(name);
      return closed(defs[name] ?? null, seen);
    }
    return branch.type === 'object' && branch.additionalProperties === false;
  };
  const enumUnions = (value: Json): Json => {
    if (Array.isArray(value)) return value.map(enumUnions);
    if (value === null || typeof value !== 'object') return value;
    const walked = Object.fromEntries(Object.entries(value).map(([key, child]) => [key, enumUnions(child)]));
    normalizeNativeKeywords(walked);
    const branches = walked.anyOf;
    if (Array.isArray(branches) && branches.length > 1 && branches.every((branch) => closed(branch))) {
      const { anyOf: _anyOf, ...rest } = walked;
      return { ...rest, oneOf: branches };
    }
    return walked;
  };
  return {
    ...bundle,
    $defs: Object.fromEntries(
      Object.entries(defs)
        .filter(([name]) => !name.endsWith('Output'))
        .map(([name, schema]) => [name, enumUnions(schema)])
    ),
  };
}

function normalizeNativeKeywords(schema: { [key: string]: Json }): void {
    if (typeof schema.$ref === 'string') {
      delete schema.title;
      delete schema.description;
    }
    // Timestamp text stays lossless on the wire. Native validates formats
    // before decoding; typify's chrono conversion would change that text.
    if (schema.type === 'string' && schema.format === 'date-time')
      delete schema.format;
    const names = schema.propertyNames;
    if (schema.type === 'object' && names !== null && typeof names === 'object' && !Array.isArray(names)
      && Object.keys(names).length === 1 && names.type === 'string')
      delete schema.propertyNames;
}

/** The native crates whose sources name the generated types they use. */
export const NATIVE_CRATES = fileURLToPath(new URL('../../../octocode-native/crates', import.meta.url));

export function renderRust(header: string, bundleJson: string, roots = nativeIdentifiers(NATIVE_CRATES)): string {
  requireTypify();
  const scratch = mkdtempSync(join(tmpdir(), 'octocode-tool-types-'));
  try {
    const input = join(scratch, 'tool-types.schema.json');
    const output = join(scratch, 'tool_types.rs');
    writeFileSync(input, JSON.stringify(rustBundle(JSON.parse(bundleJson))));
    execFileSync(
      'cargo',
      [
        'typify',
        '--no-builder',
        '--additional-derive',
        'PartialEq',
        // Deterministic iteration: rule objects feed snapshot digests.
        '--map-type',
        '::std::collections::BTreeMap',
        input,
        '-o',
        output,
      ],
      // Diagnostics stream to the caller's stderr as typify writes them: no
      // in-memory buffer to overflow, and a failure shows them before it throws.
      { stdio: ['ignore', 'ignore', 'inherit'] }
    );
    // Inner attributes cannot survive `include!`; the native contract-types
    // crate root (`crates/contract-types/src/lib.rs`) carries the equivalent `#[allow]`s.
    const generated = keepReachable(
      readFileSync(output, 'utf8')
        .split('\n')
        .filter((line) => !line.startsWith('#![') && !line.startsWith('//!'))
        .join('\n'),
      roots
    ).trim();
    // Validated string newtypes format like the `String` they wrap.
    const display = [...generated.matchAll(/^pub struct (\w+)\(::std::string::String\);$/gm)]
      .map(
        ([, name]) => `impl ::std::fmt::Display for ${name} {
    fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
        f.write_str(&self.0)
    }
}`
      )
      .join('\n');
    return `${header}\n${unicodePatterns(generated)}\n${display}\n`;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/** JSON Schema patterns use Unicode mode in both admission and typed decoding. */
function unicodePatterns(generated: string): string {
  return generated.replace(
    /::\s*regress\s*::\s*Regex\s*::\s*new\s*\(\s*("(?:\\.|[^"\\])*")\s*,?\s*\)/g,
    '::regress::Regex::with_flags($1, "u")'
  );
}
