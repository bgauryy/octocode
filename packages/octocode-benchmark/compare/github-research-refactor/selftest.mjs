import assert from 'node:assert/strict';
import {grade} from './grading.mjs';
import {admit} from './proxy.mjs';
import {stableCatalog} from '../graph-research-v1/run.mjs';
const t={owner:'o',repo:'r',ref:'abc',expected:{value:'one,two',proofs:[{path:'x',line:3,text:'deciding source'}]}};
const a={value:' one, two ',evidence:[{url:'https://github.com/o/r/blob/abc/x',line:3}]};
const c={admitted:true,name:'ghGetFileContent',args:{queries:[{owner:'o',repo:'r',branch:'abc',path:'x'}]},result:{structuredContent:{results:[{index:0,data:{files:[{path:'x',content:'deciding source\n',sourceLineRanges:[{start:3,end:3}]}]}}]}}};
let checks=0;const test=(f)=>{f();checks++;};
test(()=>assert(grade(t,a,[c])));test(()=>assert(!grade(t,{...a,value:'wrong'},[c])));test(()=>assert(!grade(t,a,[])));
test(()=>assert(!grade(t,{...a,evidence:[{url:a.evidence[0].url,line:4}]},[c])));
const bad=structuredClone(c);bad.args.queries[0].branch='wrong';test(()=>assert(!grade(t,a,[bad])));
const fake=structuredClone(c);fake.result.structuredContent.results[0].data.files[0].content='fabricated\n';test(()=>assert(!grade(t,a,[fake])));
const multi=structuredClone(t);multi.expected.proofs.push({path:'y',line:5,text:'second'});test(()=>assert(!grade(multi,a,[c])));
const denied=structuredClone(c);denied.admitted=false;test(()=>assert(!grade(t,a,[denied])));
test(()=>assert(stableCatalog([{event:'catalog',tools:['x']},{event:'catalog',tools:['x']}],['x'])));
test(()=>assert(!stableCatalog([{event:'catalog',tools:['x']},{event:'catalog',tools:['y']}],['x'])));
test(()=>assert.throws(()=>admit('localFetch',{path:'/private'},['ghGetFileContent','clasify'],t)));
test(()=>assert.throws(()=>admit('clasify',{resources:[{context:{tool:'localFetch',query:{path:'/private'}}}],questions:[{}]},['ghGetFileContent','clasify'],t)));
test(()=>assert.throws(()=>admit('ghGetFileContent',{owner:'o',repo:'r',path:'x',branch:'wrong'},['ghGetFileContent'],t)));
test(()=>assert.equal(admit('clasify',{resources:[{context:{tool:'ghGetFileContent',query:c.args.queries[0]}}],questions:[{}]},['ghGetFileContent','clasify'],t).cells,1));
console.log(JSON.stringify({checks,passed:checks}));
