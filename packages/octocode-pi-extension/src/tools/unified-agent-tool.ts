/**
 * unified-agent-tool.ts — Phase 4 facade: RFC tool-surface-unification.
 *
 * Registers a single public tool named `agent` that wraps:
 *   spawn   → typed profiles (researcher/planner/architect/browser/custom)
 *   inspect → list all agents or status of one
 *   wait    → wait for a worker turn or return a live snapshot after silence
 *   message → send/followUp to a live agent
 *   steer   → redirect in-flight turn or queue a follow-up
 *   abort   → graceful RPC interrupt without terminating the process
 *   kill    → terminate a worker process
 *
 * Agent state is projected from agent-tools.ts into this public facade.
 *
 * Browser profile delegates to routeTask + buildSpawnConfig (exported from
 * browser-agent-tool.ts) for CDP domain routing and system-prompt construction.
 *
 * Same-batch cross-reference guard: a batch that contains at least one `spawn`
 * query AND at least one lifecycle query with a non-empty `agentId` is rejected
 * before any side effect, because the caller cannot know the IDs that would be
 * generated by the spawns in the same call.
 *
 */

