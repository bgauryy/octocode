#!/usr/bin/env node
/**
 * Writes `src/team/casefold-table.generated.ts`: the Unicode full case folding that reservation path keys use, taken from the
 * table the octocode-agents-communication package freezes (`unicode16.json`, built from CaseFolding.txt statuses C and
 * F), so a path has the same key in Pi's team and in that package. Run it after the package's table changes:
 *   yarn casefold:generate
 * `tests/coordination-contract.test.ts` fails while the file differs from what this renders.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from './is-main.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const SOURCE = path.join(root, '..', 'octocode-agents-communication', 'assets', 'unicode16.json');
export const TARGET = path.join(root, 'src', 'team', 'casefold-table.generated.ts');

/** The text of `casefold-table.generated.ts` for a parsed `unicode16.json`. */
export function renderCasefoldTable(table) {
  const hex = (value) => Number(value).toString(16).toUpperCase();
  const lines = Object.entries(table.casefold)
    .map(([from, to]) => [Number(from), to])
    .sort((a, b) => a[0] - b[0])
    .map(([from, to]) => `${hex(from)}:${to.map(hex).join(' ')}`);
  return [
    '// Generated by scripts/generate-casefold.mjs from the octocode-agents-communication package\'s frozen Unicode table. Do not edit.',
    `export const CASE_FOLDING_UNICODE_VERSION = '${table.version}';`,
    '',
    '/** One `<code point>:<folded code points, space separated>` per line, in hexadecimal: Unicode full case folding (CaseFolding.txt statuses C and F). */',
    `export const CASE_FOLDING = \`\n${lines.join('\n')}\n\`;`,
    '',
  ].join('\n');
}

if (isMain(import.meta.url)) {
  fs.writeFileSync(TARGET, renderCasefoldTable(JSON.parse(fs.readFileSync(SOURCE, 'utf8'))));
  process.stdout.write(`wrote ${path.relative(process.cwd(), TARGET)}\n`);
}
