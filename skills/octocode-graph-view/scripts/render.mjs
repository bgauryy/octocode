#!/usr/bin/env node
// data.json (+ model.json beside it) -> brief.txt and brief-full.txt: measured facts only (counts, algorithm
// results, checks), each pointing to the data.json field that holds every row. The live viewer is serve.mjs.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { flags } from './lib.mjs';
import { computeMetrics } from './metrics.mjs';
import { resolveModel } from './model.mjs';

const USAGE = `usage: render.mjs --data <data.json> [--model <model.json>]
  Writes brief.txt and brief-full.txt beside data.json (computing graph metrics when data.json has none);
  --model (default: model.json beside it) adds the overlay and prints each problem to stderr.`;

const top = (D, key, n) => [...D.files].toSorted((a, b) => b.metrics[key] - a.metrics[key]).slice(0, n).map((f) => `${f.id} ${f.metrics[key]}`).join('; ');

// Unanswered LSP probes by the server's reason. Build-script-generated types (buildScriptsOff) are invisible until
// rust-analyzer runs the repository's build scripts (rustContext.buildScripts), which executes repo code: user consent.
function unansweredNote(cs) {
  const list = cs.unanswered ?? [];
  if (!list.length) return '';
  const count = new Map();
  for (const u of list) for (const r of u.reasons?.length ? u.reasons : ['unknown']) count.set(r, (count.get(r) ?? 0) + 1);
  const why = [...count].map(([r, k]) => `${r} ×${k}`).join(', ');
  const hint = count.has('buildScriptsOff') ? '; buildScriptsOff = types generated by build scripts: a rerun with rustContext.buildScripts runs the repository build.rs and needs the user\'s consent' : '';
  return `; ${list.length} probes unanswered (${why})${hint}`;
}

// Communities (size > 1) ranked by the PageRank their members hold: label, size, summed PageRank, top member.
function rankedCommunities(D) {
  const rank = new Map(D.files.map((f) => [f.id, f.metrics?.pagerank ?? 0]));
  const of = (m) => rank.get(m) ?? 0;
  return D.metrics.communities.filter((c) => c.size > 1).map((c) => {
    const lead = c.members.reduce((a, m) => (of(m) > of(a) ? m : a), c.members[0]);
    return { ...c, pagerank: c.members.reduce((s, m) => s + of(m), 0), lead };
  }).toSorted((a, b) => b.pagerank - a.pagerank);
}

const communityLine = (c) => `${c.label} (${c.size} files, PageRank ${Number(c.pagerank.toPrecision(3))}, ${Math.round(c.purity * 100)}% in ${c.chunk}, top ${c.lead})`;

function factLines(D, n) {
  const C = D.coverage, M = D.metrics, s = M.stats, v = D.verification, cs = D.callStats;
  return [
    `SECTION ${D.section}: ${C.files} files, ${C.imports} imports, ${D.symbols.length} functions, ${C.calls} calls${C.chunks > 1 ? `, ${C.built}/${C.chunks} chunks (${C.crossChunkImports} imports and ${C.crossChunkCalls} calls between chunks)` : ''}. Paths are relative to the section.`,
    `GRAPH ${s.nodes} nodes, ${s.edges} weighted production edges, total weight ${s.weight}; depth 0-${s.maxDepth}; max k-core ${s.maxCore}; modularity ${s.modularity} over ${s.communities} communities (+${s.isolated} isolated files)`,
    `COMMUNITIES by summed PageRank: ${rankedCommunities(D).slice(0, n).map(communityLine).join('; ')}`,
    `PAGERANK (weighted, importance flows to dependencies): ${top(D, 'pagerank', n)}`,
    `BETWEENNESS (bridges on shortest dependency paths): ${top(D, 'betweenness', n)}`,
    `IN-WEIGHT (imports + evidence-weighted calls received): ${top(D, 'inWeight', n)}`,
    `CYCLES ${s.cycles} strongly connected sets; ${M.cycles.slice(0, n).map((c) => `${c.size} files [${c.languages.join(',')}] in ${c.chunks.join('+')}`).join('; ')}`,
    `PACKAGES (Ca in, Ce out, I = Ce/(Ca+Ce)): ${M.packages.slice(0, n).map((p) => `${p.chunk} Ca ${p.ca} Ce ${p.ce} I ${p.instability}`).join('; ')}`,
    `FILES checked on disk: ${v ? `${v.ok}/${v.checked} match (${v.stale} stale, ${v.missing} missing, ${v.lines} with lines outside the file)` : 'not checked'}`,
    `CALLS ${cs?.lsp === 'ok' ? `cross-checked by LSP: ${cs.both} both, ${cs.graphOnly} graph only, ${cs.lspOnly} LSP only${unansweredNote(cs)}` : `graph only (${cs?.lsp ?? 'off'})`}`,
  ];
}

function modelLines(m) {
  return [
    `MODEL layers=${m.layers.map((l) => l.id).join('>') || 'none'} upward_imports=${m.upward.length}${m.upward.length ? ` (${m.upward.slice(0, 3).map((e) => `${e.source}>${e.target}:${e.line}`).join('; ')})` : ''} flows=${m.flows.map((x) => x.id).join(',') || 'none'}`,
    ...m.findings.map((x) => `FINDING [${x.confidence}] ${x.title}`),
    ...(m.warnings.length ? [`MODEL WARNINGS ${m.warnings.length}`] : []),
  ];
}

const where = 'Rows: data.json files[].metrics, metrics.cycles/communities/packages, fileEdges (weighted), files[].loc and files[].check.';

// Writes both briefs beside data.json; returns their paths.
export function writeBriefs(D, out, modelPath = join(out, 'model.json')) {
  if (!D.metrics) computeMetrics(D);
  if (existsSync(modelPath)) {
    D.model = resolveModel(D, JSON.parse(readFileSync(modelPath, 'utf8')));
    for (const w of D.model.warnings) console.error(`model: ${w}`);
  }
  const full = [...factLines(D, 10), `WEIGHT ${D.metrics.weightRule}`, ...(D.chunks ?? []).map((c) => `CHUNK ${c.path} files=${c.files} ${c.built ? 'built' : `not built${c.error ? `: ${c.error}` : ''}`}`), ...(D.model ? modelLines(D.model) : []), where];
  const brief = join(out, 'brief.txt'), briefFull = join(out, 'brief-full.txt');
  writeFileSync(briefFull, full.join('\n') + '\n');
  writeFileSync(brief, [...factLines(D, 3), `Every row, chunk and the weight rule: brief-full.txt. ${where}`].join('\n') + '\n');
  return { brief, briefFull };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--help')) { console.log(USAGE); process.exit(0); }
  const f = flags(process.argv.slice(2), { data: '', model: '' });
  if (!f.data) { console.error(USAGE); process.exit(2); }
  const dataPath = resolve(f.data);
  const out = dirname(dataPath);
  const D = JSON.parse(readFileSync(dataPath, 'utf8'));
  console.log(JSON.stringify(writeBriefs(D, out, f.model ? resolve(f.model) : undefined)));
}
