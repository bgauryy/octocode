/** Test, fixture and test-folder facts of a repository-relative path. */
export function classify(file) {
  const segments = file.split('/');
  const folders = segments.slice(0, -1);
  const testDir = folders.some(segment => TEST_DIRS.has(segment));
  return { testDir, test: testDir || TEST_FILE.test(segments.at(-1)), fixture: folders.some(segment => FIXTURE_DIRS.has(segment)) };
}

const appliesTo = (rule, file) => {
  if (!rule.ext && !rule.file) return true;
  const ext = extname(file).slice(1).toLowerCase();
  return Boolean(rule.ext?.includes(ext) || rule.file?.test(basename(file)));
};

const scoped = (entry, facts) => (facts.fixture ? entry.fixtures === true : true)
  && (entry.scope === 'any' || (entry.scope === 'test') === facts.test);

const redact = text => `${text.slice(0, 4)}…(${text.length} chars)`;

function lineStarts(text) {
  const starts = [0];
  for (let i = text.indexOf('\n'); i !== -1; i = text.indexOf('\n', i + 1)) starts.push(i + 1);
  return starts;
}

function lineAt(starts, offset) {
  let low = 0;
  let high = starts.length - 1;
  while (low < high) {
    const mid = (low + high + 1) >> 1;
    if (starts[mid] <= offset) low = mid;
    else high = mid - 1;
  }
  return low + 1;
}

/**
 * Candidate rows for one file's text. `added` (a Set of 1-based lines) limits rows to matches touching an added
 * line; `isNew` allows file-name signals when scanning a diff.
 */
export function scanText(file, text, { signals = SIGNALS, added = null, isNew = true, classifyAs = file } = {}) {
  const facts = classify(classifyAs);
  const rows = [];
  const seen = new Set();
  const starts = lineStarts(text);
  for (const entry of signals) {
    if (!scoped(entry, facts)) continue;
    for (const rule of entry.rules) {
      if (rule.path) {
        if (isNew && rule.path(file, facts)) rows.push({ file, line: null, signal: entry.signal, category: entry.category, match: basename(file) });
        continue;
      }
      if (!appliesTo(rule, file) || (rule.scope && !scoped({ ...entry, scope: rule.scope }, facts))) continue;
      for (const found of text.matchAll(rule.re)) {
        const raw = found[0];
        const offset = found.index + (raw.length - raw.trimStart().length);
        const first = lineAt(starts, offset);
        const last = lineAt(starts, found.index + Math.max(raw.trimEnd().length - 1, 0));
        if (added && !Array.from({ length: last - first + 1 }, (_, i) => first + i).some(line => added.has(line))) continue;
        const shown = raw.trim().replaceAll(/\s+/g, ' ');
        const match = entry.signal === 'credential' ? redact(shown) : shown;
        const key = `${first}\0${entry.signal}\0${match}`;
        if (seen.has(key)) continue;
        seen.add(key);
        rows.push({ file, line: first, signal: entry.signal, category: entry.category, match });
      }
    }
  }
  return rows.toSorted((a, b) => (a.line ?? 0) - (b.line ?? 0) || a.signal.localeCompare(b.signal));
}

function git(cwd, args) {
  const run = spawnSync('git', ['-c', 'core.quotePath=false', ...args], { cwd, encoding: 'utf8', maxBuffer: 1 << 30 });
  return run.status === 0 ? run.stdout : null;
}

const unquote = path => {
  if (!path.startsWith('"')) return path;
  const escapes = { n: '\n', t: '\t', '"': '"', '\\': '\\' };
  const bytes = [];
  const body = path.slice(1, -1);
  for (let i = 0; i < body.length; i++) {
    if (body[i] !== '\\') { bytes.push(...Buffer.from(body[i])); continue; }
    const octal = /^[0-7]{3}/.exec(body.slice(i + 1));
    if (octal) { bytes.push(Number.parseInt(octal[0], 8)); i += 3; } else { bytes.push(...Buffer.from(escapes[body[i + 1]] ?? body[i + 1])); i++; }
  }
  return Buffer.from(bytes).toString('utf8');
};

/** Added line numbers per file from `git diff --unified=0` text; files created by the diff are marked new. */
export function parseDiff(text) {
  const files = new Map();
  let current = null;
  let createdFile = false;
  for (const line of text.split('\n')) {
    if (line.startsWith('diff --git ')) { current = null; createdFile = false; continue; }
    if (line.startsWith('new file mode')) { createdFile = true; continue; }
    if (line.startsWith('+++ ')) {
      const target = line.slice(4);
      current = target === '/dev/null' ? null : unquote(target).replace(/^b\//, '');
      if (current) files.set(current, { added: files.get(current)?.added ?? new Set(), isNew: createdFile });
      continue;
    }
    const hunk = current && /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/.exec(line);
    if (hunk) {
      const start = Number(hunk[1]);
      const count = hunk[2] === undefined ? 1 : Number(hunk[2]);
      for (let n = start; n < start + count; n++) files.get(current).added.add(n);
    }
  }
  return files;
}

function walk(dir, out) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || WALK_SKIP.has(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile()) out.add(full);
  }
}

/** Absolute paths of the files to scan, with their added lines when diffing. */
function collect(paths, base) {
  const files = new Map(); // absolute path → { added, isNew, rel }: rel (from the repository or scan root) decides test and fixture scope
  for (const input of paths) {
    const target = resolve(input);
    if (!existsSync(target)) throw new InputError('missing-path', `${input}: no such file or directory`);
    const cwd = statSync(target).isDirectory() ? target : dirname(target);
    const top = git(cwd, ['rev-parse', '--show-toplevel'])?.trim();
    const spec = top ? relative(top, target) || '.' : null;
    if (base) {
      if (!top) throw new InputError('not-git', `${input}: --diff needs a git work tree`);
      if (git(top, ['rev-parse', '--verify', '--quiet', `${base}^{commit}`]) === null) throw new InputError('invalid-base', `${base}: not a commit in ${top}`);
      const diff = git(top, ['diff', '--no-color', '--no-ext-diff', '--unified=0', '-M', base, '--', spec]);
      if (diff === null) throw new InputError('git-failed', `git diff ${base} failed in ${top}`);
      for (const [file, entry] of parseDiff(diff)) files.set(join(top, file), { ...entry, rel: file });
      for (const file of (git(top, ['ls-files', '-z', '--others', '--exclude-standard', '--', spec]) ?? '').split('\0').filter(Boolean)) {
        files.set(join(top, file), { added: null, isNew: true, rel: file });
      }
    } else if (top) {
      for (const file of (git(top, ['ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', spec]) ?? '').split('\0').filter(Boolean)) {
        files.set(join(top, file), { added: null, isNew: true, rel: file });
      }
    } else if (statSync(target).isDirectory()) {
      const found = new Set();
      walk(target, found);
      for (const file of found) files.set(file, { added: null, isNew: true, rel: relative(target, file).replaceAll('\\', '/') });
    } else {
      files.set(target, { added: null, isNew: true, rel: basename(target) });
    }
  }
  return files;
}

const display = file => {
  const rel = relative(process.cwd(), file);
  return (rel && !rel.startsWith('..') && !isAbsolute(rel) ? rel : file).replaceAll('\\', '/');
};

function pickSignals(names, categories) {
  for (const name of names) if (!BY_NAME.has(name)) throw new InputError('unknown-signal', `${name}: not a signal; --list names them`);
  for (const name of categories) if (!CATEGORIES.has(name)) throw new InputError('unknown-category', `${name}: not a category (${[...CATEGORIES].join(', ')})`);
  if (!names.length && !categories.length) return SIGNALS;
  return SIGNALS.filter(entry => names.includes(entry.signal) || categories.includes(entry.category));
}

function parseArgs(argv) {
  const options = { paths: [], base: null, names: [], categories: [], summary: false };
  const list = value => value.split(',').map(item => item.trim()).filter(Boolean);
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') { console.log(USAGE); process.exit(0); }
    if (arg === '--list') {
      console.log(JSON.stringify(SIGNALS.map(({ signal, category, scope, description }) => ({ signal, category, scope, description })), null, 2));
      process.exit(0);
    }
    if (arg === '--summary') { options.summary = true; continue; }
    if (!arg.startsWith('--')) { options.paths.push(arg); continue; }
    const value = argv[++i];
    if (value === undefined) fail('invalid-args', `${arg} needs a value`, 2);
    if (arg === '--diff') options.base = value;
    else if (arg === '--signal') options.names.push(...list(value));
    else if (arg === '--category') options.categories.push(...list(value));
    else fail('invalid-args', `unknown option ${arg}; see --help`, 2);
  }
  if (!options.paths.length) options.paths.push('.');
  return options;
}

export function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  let signals;
  let files;
  try {
    signals = pickSignals(options.names, options.categories);
    files = collect(options.paths, options.base);
  } catch (error) {
    if (error instanceof InputError) fail(error.code, error.message, 2);
    fail('scan-failed', errorMessage(error), 2);
  }
  const rows = [];
  let scanned = 0;
  let binary = 0;
  for (const [file, { added, isNew, rel }] of [...files].toSorted(([a], [b]) => a.localeCompare(b))) {
    let buffer;
    try {
      if (!lstatSync(file).isFile()) continue;
      buffer = readFileSync(file);
    } catch {
      continue; // listed by git but deleted or unreadable in the work tree
    }
    if (buffer.subarray(0, 8000).includes(0)) { binary++; continue; }
    scanned++;
    rows.push(...scanText(display(file), buffer.toString('utf8'), { signals, added, isNew, classifyAs: rel }));
  }
  if (options.summary) {
    const tally = key => {
      const counts = {};
      for (const row of rows) counts[row[key]] = (counts[row[key]] ?? 0) + 1;
      return counts;
    };
    console.log(JSON.stringify({ ok: rows.length === 0, filesScanned: scanned, binarySkipped: binary, candidates: rows.length, byCategory: tally('category'), bySignal: tally('signal') }, null, 2));
  } else {
    for (const row of rows) console.log(JSON.stringify(row));
  }
  process.exit(rows.length ? 1 : 0);
}

if (isMainModule(import.meta.url)) main();
