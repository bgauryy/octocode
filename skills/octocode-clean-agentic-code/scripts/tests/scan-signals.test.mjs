test('every signal in the table has a sample that raises it', () => {
  assert.deepEqual(Object.keys(SAMPLES).toSorted(), SIGNALS.map(entry => entry.signal).toSorted());
  for (const [signal, [file, text]] of Object.entries(SAMPLES)) {
    const rows = scanText(file, text);
    assert.ok(rows.some(row => row.signal === signal), `${signal} not raised by ${file}: ${JSON.stringify(rows)}`);
  }
});

test('near misses, out-of-scope files and fixtures raise nothing', () => {
  for (const [file, text] of Object.entries(CLEAN)) assert.deepEqual(scanText(file, text), [], file);
});

test('credentials are scanned in fixtures too and printed redacted', () => {
  const rows = scanText('tests/fixtures/config.js', `key = "${AWS_KEY}"\n`);
  assert.equal(rows.length, 1);
  assert.equal(rows[0].signal, 'credential');
  assert.ok(rows[0].match.startsWith('AKIA') && !rows[0].match.includes(AWS_KEY), rows[0].match);
});

test('a multi-line match reports its first line, and added lines limit rows', () => {
  const text = 'ok = 1\ntry:\n    run()\nexcept Exception:\n    pass\n';
  assert.deepEqual(scanText('src/a.py', text).map(row => [row.line, row.signal]), [[4, 'empty-catch']]);
  assert.deepEqual(scanText('src/a.py', text, { added: new Set([5]) }).map(row => row.line), [4]);
  assert.deepEqual(scanText('src/a.py', text, { added: new Set([1]) }), []);
});

test('parseDiff collects added lines and marks created files', () => {
  const diff = [
    'diff --git a/src/a.js b/src/a.js', 'index 1..2 100644', '--- a/src/a.js', '+++ b/src/a.js',
    '@@ -2,0 +3,2 @@ ctx', '+console.log(1)', '+x', '@@ -10 +12 @@', '-old', '+new',
    'diff --git a/src/new.js b/src/new.js', 'new file mode 100644', '--- /dev/null', '+++ b/src/new.js', '@@ -0,0 +1 @@', '+hi',
    'diff --git a/gone.js b/gone.js', 'deleted file mode 100644', '--- a/gone.js', '+++ /dev/null', '@@ -1 +0,0 @@', '-bye',
  ].join('\n');
  const files = parseDiff(diff);
  assert.deepEqual([...files.keys()], ['src/a.js', 'src/new.js']);
  assert.deepEqual([...files.get('src/a.js').added], [3, 4, 12]);
  assert.equal(files.get('src/a.js').isNew, false);
  assert.equal(files.get('src/new.js').isNew, true);
});

function gitRepo(files) {
  const dir = mkdtempSync(join(tmpdir(), 'scan-signals-'));
  const env = { PATH: process.env.PATH, HOME: dir, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@example.invalid', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@example.invalid' };
  const write = (name, text) => { mkdirSync(dirname(join(dir, name)), { recursive: true }); writeFileSync(join(dir, name), text); };
  const git = (...args) => assert.equal(spawnSync('git', args, { cwd: dir, env }).status, 0, `git ${args.join(' ')}`);
  for (const [name, text] of Object.entries(files)) write(name, text);
  git('init', '-q');
  git('add', '.');
  git('commit', '-q', '-m', 'base');
  return { dir, env, write };
}

const scan = (args, cwd, env) => {
  const result = spawnSync(process.execPath, [script, ...args], { cwd, encoding: 'utf8', env });
  return { status: result.status, rows: result.stdout.split('\n').filter(Boolean).map(line => JSON.parse(line)) };
};

test('--diff reports only lines added since the base, plus untracked files, and skips ignored files', () => {
  const { dir, env, write } = gitRepo({ '.gitignore': 'ignored.js\n', 'src/app.js': "console.log('old');\n" });
  try {
    write('src/app.js', "console.log('old');\nconst a = 1;\nconsole.log('new');\n");
    write('src/extra-v2.js', 'debugger;\n');
    write('ignored.js', "console.log('ignored');\n");
    const { status, rows } = scan(['--diff', 'HEAD'], dir, env);
    assert.equal(status, 1);
    assert.deepEqual(rows.map(row => [row.file, row.line, row.signal]), [
      ['src/app.js', 3, 'debug-print'],
      ['src/extra-v2.js', null, 'iteration-sibling'],
      ['src/extra-v2.js', 1, 'debug-print'],
    ]);
    const whole = scan(['src'], dir, env);
    assert.deepEqual(whole.rows.filter(row => row.file === 'src/app.js').map(row => row.line), [1, 3]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('invalid input exits 2: unknown signal, a base that is not a commit, --diff outside git', () => {
  const { dir, env } = gitRepo({ 'a.js': 'x\n' });
  const plain = mkdtempSync(join(tmpdir(), 'scan-signals-plain-'));
  try {
    const bad = args => {
      const result = spawnSync(process.execPath, [script, ...args.slice(1)], { cwd: args[0], encoding: 'utf8', env });
      return { status: result.status, code: JSON.parse(result.stdout).error.code };
    };
    assert.deepEqual(bad([dir, '--signal', 'nope']), { status: 2, code: 'unknown-signal' });
    assert.deepEqual(bad([dir, '--diff', 'no-such-ref']), { status: 2, code: 'invalid-base' });
    assert.deepEqual(bad([plain, '--diff', 'HEAD']), { status: 2, code: 'not-git' });
    const clean = spawnSync(process.execPath, [script, '--summary'], { cwd: dir, encoding: 'utf8', env });
    assert.equal(clean.status, 0);
    assert.deepEqual(JSON.parse(clean.stdout), { ok: true, filesScanned: 1, binarySkipped: 0, candidates: 0, byCategory: {}, bySignal: {} });
  } finally {
    rmSync(dir, { recursive: true, force: true });
    rmSync(plain, { recursive: true, force: true });
  }
});
